// ============================================================================
//  术式系统 Schema v1 · 场景
// ============================================================================
//
//  场景 = 一场遭遇的**全部初始条件**。
//
//    技能 Skill        零件，玩家编辑它
//    术式 Technique    编排，玩家释放它
//    场景 Scenario     舞台，玩家在它里面打
//
//  场景是第三种内容，也是最外面的一层。它只描述"开局时世界里有什么"，
//  不含任何行为 —— 行为全在技能和术式里。
//
//  ⚠ 为什么场景必须是内容而不是代码
//
//    在它进 schema 之前，网页端的开局是 main.ts 里的一段硬编码数组：
//    玩家带哪五个术式、三个敌人站哪儿、各多少血，全写在代码里。
//    结果是**每加一个技能都要改引擎代码**，而且玩家选不到它 ——
//    裂魂和名刀司命做完了却不在 loadout 里，等于没做。
//
//    这和 manifest.json 那条注释是同一个道理：
//    硬编码的清单迟早和实际内容对不上。
//
//  ⚠ 场景是**无头**的
//
//    它不知道自己是给浏览器玩的还是给命令行跑的。
//    同一份场景，`npm run battle` 拿它跑一场可重放的 AI 对殴，
//    浏览器拿它当开局 —— 区别只在于有没有哪一方是 controlledBy: 'human'。
// ============================================================================

import type { AiProfile } from './skill-schema.ts'

/**
 * 阵营。
 *
 * ⚠ 定义在这里（schema）而不是 sim 里：场景是内容，内容要能写它。
 *   src/sim/types.ts 从这里再导出一次，别在两处各写一份。
 */
export type Faction = 'player' | 'enemy' | 'neutral'

/** 场景里的一个单位。开局时按它生成一个实体 */
export interface ScenarioEntity {
  /**
   * 给人看的名字。战报、血条、报错都用它。
   *
   * ⚠ 它**不是** id —— 引用实体请用 id。改名不该破坏任何引用。
   */
  label: string

  faction: Faction

  /** 出生点，米 */
  pos: { x: number; y: number }

  /** 标签。条件里的 hasTag、AI 的 targetTags、抗性匹配都看它 */
  tags?: string[]

  /**
   * 基础属性。写的是**上限**那类派生属性的基底，
   * 开局自动满血满蓝（除非再写 stored）。
   *
   * 例：{ 'char.hp.max': 300, 'char.speed': 4.5 }
   */
  attributes?: Record<string, number>

  /**
   * 存储属性的初始值。一般不用写 —— 不给就按上限拉满。
   * 要开局残血（比如"第二形态剩 30% 血"）才用得上。
   */
  stored?: Record<string, number>

  /** 带在身上的术式 id。玩家按数字键选的就是这个列表 */
  techniques?: string[]

  /**
   * 开局就已经挂上的常驻术式。
   *
   * ⚠ 和 techniques 的区别：techniques 是"能按"，这只是"已经在生效"。
   *   被动的技能图钩子（名刀司命那种）必须走这里，否则挨打时钩子还没挂上。
   */
  activeTechniques?: string[]

  /**
   * 谁在驱动它。
   *
   * 不写就按有没有 ai 推断：写了 ai = 'ai'，没写 = 'human'。
   * 大多数情况不用写 —— 但如果一个没 ai 的木桩出现在纯 AI 的对殴里，
   * 不写就会被当成玩家，所以那种情况要显式写 'ai'。
   */
  controlledBy?: 'human' | 'ai'

  /** AI 配置。只有 controlledBy 是 'ai' 时才有意义 */
  ai?: AiProfile

  /** 活多久后自动消失（秒）。不写 = 一直活着。召唤物、投射物型单位用 */
  lifetime?: number

  /** 碰撞半径，米。不写就用引擎默认的 0.4 */
  radius?: number

  /**
   * 这是个**什么东西**。不写 = `'actor'`（会动、会打、有 AI 的那种）。
   *
   * ⚠ `'item'` 是 2026-09-21 才有的：**掉在地上的一件东西**。
   *   现在的用途只有一个 —— **地上的武器**（`weapon` 字段）。
   *
   *   玩家 2026-09-21 给的前提：
   *   > 换武器的前提是武器有建模，能作为实体被交互。
   *
   *   所以武器必须先是一个**实体**：有位置、能被看见、能被走过去捡起来。
   *   不然"换武器"就只是一个改数字的菜单，和这个游戏的世界没有关系。
   *
   *   `'item'` 的实体：
   *   · 不动（没有 AI、没有速度），不参与碰撞、不进区域、不挨打
   *   · 可以被附近的人**捡起来**（`equipItem` / `pickupNearby`）
   *   · 捡走之后这件东西就没了（人手上那把会掉在原地 —— 见 equip.ts）
   */
  kind?: 'actor' | 'item'

  /**
   * 身上带的**武器**（`content/weapons/` 里的 id）。
   *
   *   `kind: 'actor'` → 开局就拿着它
   *   `kind: 'item'`  → 地上躺着的就是这把
   *
   * ⚠ 写的是 **id**，不是把属性抄在这里：武器的属性只有一份（`content/weapons/`），
   *   抄一份到场景里，改武器时就得改两处，而且改漏的那一处没有任何提示。
   */
  weapon?: string
}

/**
 * 一场遭遇。
 *
 * 游戏模式和场景是"多对多"的：一场 duel 既能当无头基准测试，
 * 也能被玩家接管一方来打。所以场景里**不写**模式。
 */
export interface Scenario {
  schemaVersion: number

  /** 内容的唯一 id，形如 `scenario.duel` */
  id: string

  name: string

  /** 打多少秒之后判定结束。不写 = 不限时（浏览器里就是打到死为止） */
  duration?: number

  /**
   * 随机种子。
   *
   * ⚠ 同一个种子 + 同一份场景 = 逐帧一样的一场战斗。
   *   这是 core-sim 的纪律换来的，也是"复现一个 bug"的唯一办法。
   */
  seed?: number

  /** 参战单位。顺序就是生成顺序，所以也是实体 id 的顺序 */
  entities: ScenarioEntity[]
}
