/**
 * 单条点数记录。
 *
 * ⚠ **全部是算出来的，一个字都不存进 JSON。**
 *
 *   第一版把点数写在规则和阶段上（`Rule.points` / `Phase.points`），
 *   结果玩家把"30 伤害"改成"300 伤害"，点数纹丝不动 ——
 *   等于可以白嫖。做编辑器的时候实测踩到的。
 *
 *   现在的规矩：**点数由内容推导**。你改数值，点数自己跟着变。
 *   定价表在 `content/balance.json` 的 `rates` 里。
 */
export interface PointEntry {
  label: string
  points: number
  /** 来源：规则 / 阶段 / 买卖规则条数 */
  from: 'rule' | 'phase' | 'ruleSlots'
  refId?: string
  /** JSON 路径，报错时用来定位 */
  path: string
}

/** 一个技能（或术式）的点数账。整份都是算出来的 */
export interface PointBalance {
  /** 合计。普通技能必须为 0 */
  total: number
  /**
   *   'normal'   普通，total 必须为 0
   *   'negative' 负值（超模），total < 0，使用时按 |total| 消耗血契
   */
  kind: 'normal' | 'negative'
}


// ============================================================================
//  十、顶层：技能 / 术式
// ============================================================================

/**
 * 技能：**玩家编辑的单位**。一次释放，由阶段和规则组成。
 *
 * 挥砍是一个技能（起手 → 挥砍 → 收招）。火球是一个技能。
 * 编辑器的面板里编辑的是它。
 */
export interface Skill {
  schemaVersion: number
  id: string
  name: string
  /**
   * **技能介绍**：写给玩家看的，显示在技能编辑器最上面。
   *
   * ⚠ 玩家 2026-09-21 要的：
   *   > 技能要在编辑器中有技能介绍。（不必一句话，要介绍清楚）
   *
   * ⚠ 它是**唯一允许手写**的那类说明 —— 另一类（"造成 30 点伤害"那种）
   *   必须从数据生成，因为手写的数字会和数值脱节。
   *   所以这里的规矩是：**不许写数字**（校验器报 `NOTE_WITH_NUMBER`）。
   *   写"打得很痛"可以，写"造成 30 点伤害"不行 —— 后者交给生成的那一栏。
   *
   * ⚠ 它和 `_comment_*` 的区别：那些是写给**作者**的（设计推理、踩过的坑、⚠），
   *   又长又带数字；这一条是写给**玩家**的，读起来要像说明书，不像笔记。
   */
  note?: string
  /**
   * ---- **这份技能是从哪个基础技能长出来的**（= 自定义技能库里的变体）----
   *
   * ⚠ 玩家 2026-09-21 定的模型（**两个库**）：
   *   > 技能是玩家拥有的东西，存在两个库：**基础技能库**（我们写的出厂配平为 0 的那些）、
   *   > **自定义技能库**（玩家进行编辑后的技能另存一份副本在这里）。
   *   > 技能可以存在多个变体，玩家给它们取名字（不取就是默认「火球-副本1」这种名字）。
   *   > 技能不是独属于一个术式的，应该影响所有用到它的术式，但要注意
   *   > **基础技能和它的变体是两样东西**……自定义技能是独立的，它不属于术式。
   *
   * 所以：
   *
   *   · **基础技能库** = `content/skills/*.json`：出厂内容，**只读**，永远是 0 点，
   *     也是"创造一个技能"时可选的**模板**。
   *   · **自定义技能库** = 玩家创造出来的变体，存在**存档**里（不在内容里）。
   *     它们有自己的 id（`custom.<模板短名>.<序号>`）和名字。
   *   · 术式**按 id 引用技能**，两个库都能引用 —— 同一份术式里
   *     "基础版"和"我的变体版"完全可以同时出现（它们是两样东西）。
   *
   * ⚠ `basedOn` 是**账的基准**：变体的点数 = **它相对这个基础技能**的偏离
   *   （宗旨：默认值下配平为 0）。所以一个变体改一次，**所有用到它的术式**
   *   都会跟着多出/少掉同一笔差价 —— 这正是"影响所有用到它的术式"。
   *
   * ⚠ 从一份**变体**再"另存为"出来的新变体，`basedOn` 仍然是**最初那个基础技能**
   *   （不是上一份变体）：账永远是"偏离出厂版多少"，不然变体一旦成链，
   *   "出厂配平为 0"这条宗旨就断了（A 偏离 +5、从 A 派生的 B 再 +5，
   *   而 B 只显示 +5、实际偏离出厂 +10）。
   *
   * ⚠ 不写 = 它本身就是基础技能（出厂内容）。
   */
  basedOn?: string
  /**
   * ---- **系别**：这个技能是武器系还是魔法系 ----
   *
   * ⚠ **派生字段：不写进 JSON。** 它由加载器**按目录**盖上去
   *   （玩家 2026-09-21 定的："技能的系别看目录"）：
   *
   *     content/skills/*.json         → 'magic'（技能库 —— 玩家编辑的就是它）
   *     content/weapon-skills/*.json  → 'weapon'（武器技能模板，`readonly` 那一批）
   *     存档里的自定义技能             → 'magic'（武器技能是只读模板，
   *                                     玩家做不出武器系的变体）
   *
   * ⚠ **为什么不加一个 JSON 字段、也不看 `tags` 里的「武器技能」：**
   *   那样就有了**两份会漂移的真相**，而它们漂移的方式是**静默的** ——
   *   标签漏写不会报任何错，它只会把一个武器技能判成魔法系
   *   （编辑器给错技能库、校验器放行一门混了系别的术式）。
   *   **目录是唯一看得见、不会漏写的事实**，所以系别在加载时从目录推，
   *   推导只在一个地方：`technique-system/src/school.ts`。
   *
   * ⚠ 这个字段**缺失**时校验器会报 `SKILL_SCHOOL_MISSING`：
   *   "判不了同不同系"不许静默通过（那条错的意思是"你这张技能表
   *   不是走加载器建的"，不是内容写错了）。
   */
  school?: SkillSchool
  /**
   * **只读**：作者写死的固定件，编辑器里不给改（连滑块都不显示）。
   *
   * ⚠ 玩家 2026-09-21 定的：
   *   > 武器技能（横批、旋转斩、刺击等等）是**不能**在编辑器修改属性的，
   *   > 每种武器的技能范围和伤害也因为属性不同而不同……
   *   > 玩家能改的只有它们**如何组成武器术式**。
   *
   * 所以武器技能模板都带这个标记。它和"这个字段引擎不读"不一样 ——
   * 这是**故意不该被改**，不是没实现。
   *
   * ⚠ 想改一把武器的强度，改的是**武器的属性**（那会代入到技能里），
   *   或者换一把武器 —— 而不是去改技能本身。
   */
  readonly?: boolean
  /*
   * ⚠ 这里原来有个 `factoryDebt?: boolean`（"出厂就负债的零件"）。
   *
   *   它是 2026-09-21 那一轮加的：切到"相对出厂值"的账之后，裂魂和血祭斩
   *   就不再是负值术式了、血契会没有出厂消费者，所以给技能开了一道**显式口子**。
   *
   *   **同日删掉了**，玩家看完之后的判断是"没什么必要"：
   *
   *     · 宗旨（每个技能在它自己的默认值下是 0 点）是**铁的**：
   *       为了两个出厂示范开一道口子，不值。
   *     · 更要紧的是它在**变体**上说不通。玩家原话：
   *       > **负债件的变体不一定是负债件**。
   *       而当时实现判的是"模板有没有这个标记"，所以变体是**一定**继承 ——
   *       把裂魂改弱之后，那个术式反而会拿到一大笔额度，算法却还是"负债件"那套。
   *
   *   现在：**出厂内容全是 0 点**，一个例外都没有。
   *   想超模就自己编变体（`basedOn`），用血契付 —— 那本来就是血契要服务的东西。
   */
  /**
   * ---- **施法形态**：这次释放要不要一条时间轴、要多长 ----
   *
   * ⚠ **不写 = `'instant'`（瞬发）**。理由（默认值、相对施法者、和激活方式的区别）
   *   全写在上面 `SkillForm` 的注释里，这里只强调最容易读岔的那一点：
   *
   *   形态是**技能自己**的事实（这一段要不要时间轴），
   *   激活方式（`Technique.activation`）是**术式**的事实（玩家怎么按）。
   *   "图腾是瞬发"就是这么来的：放下去那一下有完整时间轴，
   *   图腾之后怎么活着是那个**实体**的事。
   *
   * ⚠ 内容里只标**不是瞬发**的那些（今天的真实数字：6 个 `passive` + 1 个 `charged`，
   *   一个 `sustained` 都没有 —— **不要为了演示新造技能**）。
   *   判据按机制推、不凭感觉：只被 `auto` 术式用到的 / 时间轴里只有占位相的 → `passive`；
   *   有 `duration: -1` 那一段（由玩家控制时长）的 → `charged`。
   */
  form?: SkillForm
  /**
   * ---- **瞄准**：这个技能怎么解释那**一个意图** ----
   *
   * ⚠ 2026-09-21（日志 47）它从**术式 / 序列段**搬到了这里 ——
   *   定稿（[`docs/sequence-and-modifier-model.md`](../docs/sequence-and-modifier-model.md) §六 / §九）：
   *   **术式没有瞄准，序列段也没有**；瞄准住在技能上。
   *   旧的 `Technique.targeting` 和 `SequenceSegment.targeting` **已经删掉**
   *   （校验器会对着写回去的报错，见下面那条 ⚠）。
   *
   * 三条规矩（和那两处旧字段的语义**一模一样**，只是换了个住处）：
   *
   * 1. **默认是"鼠标方向"** —— 不写就按鼠标方向打（= `directional`）✓
   *    ⚠ 这一条今天只是**默认值的语义**，不是代码里的兜底：出厂内容的每份技能
   *      都**显式写着**自己的瞄准（迁移时逐条搬的，见日志 47 的对照表）——
   *      为的是让"这个技能的瞄准是从哪儿来的"能**一条一条说出来**，
   *      而不是靠默认值糊过去。
   * 2. **每个技能单独判断**（玩家定的）✓ —— 不再由术式统一决定。
   *    ⇒ 引擎里唯一读它的地方是**编译**：术式本身不再有瞄准，
   *      编译产物那份 `targeting` 是从技能身上**取**来的（`compile.ts` 的
   *      `targetingOfChain`），所以 `resolveAim` / 管线 / AI **一行都没改**。
   * 3. **"自动锁敌"和"对自己"的技能直接忽略它** ✓ ——
   *    `auto` / `locked` 自己挑目标，`self` 连意图都不看。
   *    ⚠ 只有 `directional` / `areapoint` 真的**用**意图里的方向和落点。
   *
   * ⚠ **意图 ≠ 瞄准方式**（§九，最容易读岔的一条）：
   *   · **意图** = 玩家**这一次激活**给出的那**一个**指向 ——
   *     今天的客户端始终只收集"**鼠标位置那一个点**"（方向、落点都从它推出来）；
   *   · **瞄准方式**（这个字段）= 这个技能**怎么解释**那一个意图。
   *   混起来的表现是"两个技能都想自己拿一个意图"，而一次输入只有一份。
   *   ⇒ 所以客户端**不再按术式的 mode 决定收集什么**，技能各自解释同一个点 ✗
   *      （旧写法：按 `Technique.targeting.mode` 决定给方向还是给落点）。
   *
   * ⚠ 字段清单一字未变（`mode` / `valid` / `range` / `requireStatusTag`）：
   *   这次是**行为等价的搬家**，不是重新设计瞄准。
   *   `valid` 决定"这次动作能作用到谁"，`range` 的语义按 `mode` 分
   *   （`areapoint` 是"落点最远能放多远"，别的模式是"打得到多远"）。
   */
  targeting?: Targeting
  /** 时间轴 */
  phases: Phase[]
  /**
   * **固有效果**：这个技能是什么（见 `SkillEffect`）。
   *
   * ⚠ 可以不写 —— 有些技能确实**没有效果**，只有反应：
   *   血契记账器（`skill.blood-pact`）、背水（`skill.last-stand`）、
   *   猎手直觉、无下限、迟滞场…… 它们是"挂上就一直在起作用"的被动。
   */
  effect?: SkillEffect[]
  /** 规则列表：**额外的行为与反应**。玩家拖拽决定 order */
  rules: Rule[]
  /**
   * 规则条数上限。初始有值，可以花点数增加，也可以降低上限换点数。
   * 这是"复杂度税"：防止复杂技能永远优于简单技能。
   */
  ruleSlots: number
  tags?: string[]
}

/**
 * 术式里技能之间的**连接**。
 *
 * 这是"术式 = 编程组合"里那个**编程**的地方。
 * 没有它的话，术式只是"把几个技能的阶段接起来"——
 * 每一段都会无条件执行，写不出"位移过去，碰到了才炸"。
 *
 * ⚠ 它是**平行数组**：`links[i]` 管的是 `skills[i+1]` 要不要执行。
 *   第 0 个技能永远执行（总要有个起点），所以 `links` 的长度是
 *   `skills.length - 1`。
 *
 * ```
 * skills: ["skill.dash",              "skill.shock"]
 * links:  [ { if: [prevHit] } ]       ← 决定 skill.shock 跑不跑
 * ```
 *
 * ⚠ 条件不成立**不是失败**，是**跳过那一段**，继续往后走。
 *   所以"没碰到就不炸"和"没碰到就炸自己"是同一个机制的不同写法，
 *   不是两种机制。
 */
export interface SkillLink {
  /**
   * 满足才进入下一段。不写 = 无条件进入（上一段结束就进）。
   *
   * 可用的条件里，`prevHit` 是专门为这里准备的：
   * 它问的是"**上一段技能有没有作用到任何人**"。
   */
  if?: Condition[]
  /** 说明这条连接是干什么的（生成的人话会用它） */
  note?: string
  /**
   * 条件不成立时跳到哪里。
   *
   * 不写 = 跳到**下一段**（也就是"这段不跑了，接着看后面"）。
   * ⚠ 目前只支持"往后跳"，不支持往回跳 —— 循环会让"这次施法什么时候结束"
   *   变得很难说清楚，而且技能是"一次释放"，本来就不该循环。
   */
  elseTo?: number
}

/**
 * **一条序列**（内联在术式里的那一层，见 `Technique.sequences`）。
 *
 * 一条序列 = **若干技能 + 它们之间的条件门**（+ 一个给人看的名字）。
 * "按一次走一段"里的那个"段"就是它。
 *
 * ⚠ **它没有 `activation` / `skills` 和 `sequences` 二选一那套** ——
 *   序列在"激活方式"上位于术式层级的下方（玩家按的是父术式那个键），
 *   所以它的激活方式是**继承**父术式的，不单独写。
 */
export interface SequenceSegment {
  /**
   * ---- **这一段的 id**（不写就由编译器合成 `<父术式id>.seq<序号>`）----
   *
   * ⚠ 它存在的理由只有一个，而且是个**兼容**理由：**冷却键是它**。
   *
   *   冷却存在 `cd.<术式id>` 这个存储属性上（见 `README` 的"冷却存在存储属性上"），
   *   而序列内联之前，每一段的"术式 id"就是它原先那份子术式的 id
   *   （`tech.ws-slash` / `tech.blink-step`）—— 也就是说
   *   **`cd.tech.blink-step` 这个键是对外可观察的行为**，不只是内部细节。
   *
   *   所以迁移时（2026-09-21，日志 46）内容里这几段把旧 id **显式写下来**，
   *   编译出来的冷却键和逐字节行为才一个都没变。
   *
   * ⚠ **新写的序列不写它** —— 让编译器按 `<父id>.seq<i>` 合成一个稳定的键。
   *   那个键和父术式、和这一段的序号绑定，改别的地方不会让它漂。
   */
  id?: string
  /**
   * 这一段叫什么（编辑器里显示）。不写就是"第 N 段"。
   *
   * ⚠ 它**不影响行为**，和 `Skill.name` 一样只是给人看的。
   *   旧模型里这个名字住在子术式上（`tech.ws-slash` 的 `name: '横砍'`），
   *   内联时照搬过来了。
   */
  name?: string
  /** 这一段按顺序执行的技能 id。和 `Technique.skills` 同一套语义 */
  skills: string[]
  /**
   * 这一段**内部**技能之间的连接条件（平行数组：`links[i]` 管 `skills[i+1]`）。
   *
   * ⚠ 和 `Technique.links` 是同一套东西 —— 一条序列里也可以写"上一段打中了才进下一段"。
   *   不写 = 全部无条件。
   */
  links?: SkillLink[]
  /*
   * ⚠ 这里原来有个 `targeting?: Targeting`（"这一段的瞄准"，日志 46 内联时的过渡遗留）。
   *
   *   **2026-09-21（日志 47）删掉了** —— 瞄准搬到**技能层**（`Skill.targeting`），
   *   序列段和术式一样**不带瞄准**。定稿见
   *   [`docs/sequence-and-modifier-model.md`](../docs/sequence-and-modifier-model.md) §六 / §九。
   *
   *   ⚠ 那次搬家是**行为等价**的：段上原先写的那份瞄准，逐字搬到了**那一段里的技能**上
   *     （`tech.blink-step` 的 `requireStatusTag: 'marked'` 搬到了 `skill.blink` ——
   *      少了它「瞬影」会闪到**最近的**敌人背后，`tests/blink.ts` 钉的正是这一条）。
   *
   *   ⚠ 别把它加回来：校验器会对着段里写回去的 `targeting` 报 `TARGETING_MOVED_TO_SKILL` ✗
   *     （术式那一层同样报 —— 防回潮是这次的两条硬检查之一）。
   */
  /**
   * ---- **这一段的修饰副本**（修饰技能，日志 48）----
   *
   * ⚠ 玩家 2026-09-21 定的红线：**不许把修饰混进 `skills: string[]`**。
   *   那样就得让每一处 `skills` 的读者重新判"这个字符串是不是技能"，
   *   而那会把上一片（序列内联、瞄准搬家）的成果全部推翻。
   *   ⇒ 副本并列在这里，用 `at` 说"我修饰它后面第几个技能"。
   *
   * ⚠ **副本只属于这份术式**（定稿 §八）：它**不进技能库**、别的术式引用不到；
   *   术式"另存为"时**副本跟着深拷贝**，之后两份互相独立。
   *   （普通技能相反：序列里存的是**引用**，另存为不深拷贝。）
   *
   * ⚠ **一条序列里不叠同类**（定稿 §八 的硬规矩）：两个「多重释放」会炸成
   *   4 个、8 个，账也算不清。所以同一段里**同类 `kind` 只能有一个副本** ——
   *   由 `MODIFIER_STACKED_KIND` 盯着。
   */
  mods?: SegmentMod[]
}

