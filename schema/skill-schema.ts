//  五、状态（控制、护盾、霸体、龟壳……全是它的变体）
// ============================================================================

// ⚠ 这里原来有个 `StatusDisable { capability: Capability }`。
//   它是**孤儿类型**：全仓库零引用，而且 `StatusDef.disables` 早就改成了
//   裸的 `Capability[]`（['move','attack','cast']），根本不用包一层对象。
//   留着它只会让人以为两种写法都行。

/** 属性修饰 */
export interface AttributeMod {
  /** 点分路径：'char.critRate' / 'char.speed' / 'skill.cooldown' */
  path: string
  op: ModifierOp
  value: ValueSpec
}

/** 状态的移除规则 */
export interface RemovalRule {
  /** 带这些标签的移除请求对它无效，例如 ['dispel'] */
  immuneTo?: string[]
  /** 只有这些来源能移除它（技能/状态 id）。神锋无影的创伤就靠这个 */
  onlyBy?: string[]
  /** 是否能被时间自然消解 */
  expires?: boolean
}

/** 层数规则 */
export interface StackRule {
  max: number
  /** refresh 刷新时长 | stack 叠层 | independent 各自独立 */
  behavior: 'refresh' | 'stack' | 'independent'
}

/**
 * 状态定义。它是"容器"：装标签、装能力禁用、装属性修改、装管线钩子。
 *
 * 四个经典效果就是它的四种装法：
 *   冻结 = disables: ['move','attack','cast']
 *   护盾 = hooks: [{ stage: 'absorb', ... }]
 *   霸体 = immuneTags: ['hardCC']
 *   龟壳 = hooks: [{ stage: 'modify', 伤害转治疗 }]
 */
export interface StatusDef {
  id: string
  name: string
  /** 标签：debuff / buff / hardCC / softCC / dot / fire / undead ... */
  tags: string[]
  /** 时长（秒）。-1 表示永久 */
  duration: number
  stack?: StackRule
  /** 禁用能力（控制效果） */
  disables?: Capability[]
  /** 免疫带这些标签的状态（霸体） */
  immuneTags?: string[]
  /** 属性修饰 */
  modifiers?: AttributeMod[]
  /** 伤害管线钩子（护盾、伤转治疗、免疫致命伤） */
  hooks?: PipelineHook[]
  removal?: RemovalRule
  /** 可见性。0 = 完全隐形（隐身精英） */
  visibility?: number
  /**
   * **阵营覆盖**（魅惑就是它）。
   *
   * 挂着这个状态时，实体**现在**算哪一边由它决定；状态一没就还原。
   * 用 `duration: -1` 写就是永久的（真正的叛变），
   * 写时长就是临时的（精神控制）。
   *
   * ⚠ `'caster'` = "跟**挂上这个状态的那个人**同一阵营" ——
   *   和 `EntityDef.faction` 用的是同一个词、同一个意思。
   *   它在施加的那一刻就解析成具体值（见 `src/sim/status.ts`）。
   *
   * ⚠ 引擎里**只有** `factionOf()` 一处读阵营。所有需要知道"谁打谁"的地方
   *   （目标选择、找敌人、找友军、AI、HUD 的敌人计数）都走它。
   *   直接读 `entity.faction` 的表现是"被魅惑的敌人还在打你，只是颜色变了"。
   */
  faction?: 'caster' | 'player' | 'enemy' | 'neutral'
  /**
   * ⚠ 这里也**没有** `points` —— 状态的点数由它改的属性、禁用的能力、
   *   挂的钩子、以及持续多久推导出来。见 src/pricing.ts。
   */
  /** 视觉提示：玩家必须能一眼看出身上有什么 */
  vfx?: string
}

/** 挂在伤害管线某一步上的钩子 */
export interface PipelineHook {
  stage: PipelineStage
  /** 同一 stage 内的排序。数字小的先执行 */
  priority?: number
  /** 何时生效：例如 onLethalDamage */
  when?: TriggerEvent
  /**
   * 触发间隔（秒）。**只对 when 是 onTick 有意义**。
   *
   * 不写就按 1 秒。持续伤害 / 持续扣能量的钩子靠它限速 ——
   * 不限速的话一秒触发 60 次。
   */
  every?: number
  /**
   * 这个钩子长在哪一侧。
   *
   *   'target'（默认）—— 宿主**被打**时生效：护盾、龟壳、名刀、反伤、亡灵反转
   *   'source'        —— 宿主**打人**时生效：吸血、增伤
   *   'any'           —— 两边都生效
   *
   * ⚠ 这个字段不能省。没有它的话，反伤在"自己打人"时也会触发 ——
   *   于是"B 反伤 A"这发伤害又触发 B 的反伤，无限弹到自己身上。
   *   这个 bug 真的踩过。
   */
  side?: 'target' | 'source' | 'any'
  if?: Condition[]
  /** 钩子要做什么。纯吸收型的钩子（护盾、次数盾）可以省掉 */
  then?: Action[]
  /** ⚠ 没有 points 字段 —— 钩子的点数由它做的事推导。见 src/pricing.ts */
  /**
   * 只在 absorb 阶段有意义：这个钩子提供多少吸收量。
   *
   *   护盾   = { mode: 'damage', perStack: 500 }   吸收 500 点伤害
   *   次数盾 = { mode: 'hits',   perStack: 1   }   挡 1 次命中
   *
   * 两者是**同一个位置、不同的消耗规则**，所以不需要两种载荷。
   * 剩余池子存在运行时的 status.vars.pool 里，用完状态就消失。
   */
  absorb?: {
    mode: 'damage' | 'hits'
    /** 每一层提供多少。damage 模式是点数，hits 模式是次数 */
    perStack: number
  }
}


// ============================================================================
//  六、规则
// ============================================================================

/**
 * 一条规则。整个系统的最小可编辑单位。
 *
 *   当【when】  若【if】  则【then】
 *   例如：当【命中时】若【目标带月光印记】则【重置本技能CD】
 */
export interface Rule {
  id: string
  /** 玩家备注，方便读懂自己的配置 */
  note?: string
  when: TriggerEvent
  /** 当 when 是 phaseEnter / phaseComplete / phaseInterrupt 时必填 */
  phaseId?: string
  if?: Condition[]
  then: Action[]
  /**
   * ⚠ 这里**没有** `points` 字段 —— 规则的点数由它做的事推导出来。
   *
   *   第一版是手写的，结果玩家把"30 伤害"改成"300 伤害"，点数纹丝不动，
   *   等于可以白嫖。做编辑器的时候实测踩到的。
   *   定价表在 balance.json 的 rates 里，算法在 src/pricing.ts。
   */
  /**
   * 触发间隔（秒）。**只对 onTick 有意义**。
   *
   * 不写的话 onTick 是每个 tick 都触发（60/秒）——
   * "每 0.5 秒扣 3 能量" 必须写 `every: 0.5`，
   * 否则会变成每秒扣 180 点。这个坑真踩过。
   */
  every?: number
  /** 玩家拖拽决定的执行顺序（同一时机内） */
  order: number
}

/**
 * 技能的**固有效果**：这个技能**是什么**。
 *
 * ⚠ 玩家 2026-09-21 定下来的第 1 条：
 *   > 技能本身的效果**不计入规则栏中**，也不具有点数盈亏。
 *
 * 所以它从 `rules` 里搬出来了，单独一块。区分标准是**机制还是反应**：
 *
 * | | 是什么 | 放哪儿 | 例子 |
 * |---|---|---|---|
 * | **固有效果** `effect` | 这个技能**是什么**：时间轴走到这一段就发生 | 这里 | 挥砍造成伤害 · 传送 · 竖一堵墙 |
 * | **规则** `rules` | 这个技能**额外做了什么**：挂在某个时机上的反应 | 那边 | 命中时回能量 · 击杀时刷新冷却 · 被暴击时反伤 |
 *
 * ⚠ 判据是机械的、可判的：**`when === 'phaseComplete'` 的那些就是固有效果**
 *   （时间轴的一部分），其余的（`onHit` / `onCast` / `onTick` / `onLowHp` …）
 *   是反应，留在 `rules` 里。
 *
 * ⚠ **"不具有点数盈亏"怎么理解**（问过玩家，选的是"机制免费、数值偏离默认才计价"）：
 *   机制**这一条**本身不产生点数（不像"多一条规则"那样要花钱）；
 *   但它里面的**数值**（伤害、距离、时长）偏离出厂值时照常计价 ——
 *   否则"位移的距离有代价"就没地方落脚了。
 *   在宗旨下这两件事是一回事：出厂技能的账本来就是 0。
 *
 * ⚠ 引擎那边**不需要新概念**：编译时它被折成一条 `when: 'phaseComplete'`
 *   的规则（见 `src/effects.ts`）。所以这次搬家对行为是**零改动**，
 *   对账也是零改动 —— 换的只是数据形状和界面归属。
 */
export interface SkillEffect {
  /** 技能内唯一。账和报错都按它认身份（**不按下标** —— 拖一下顺序就对错了） */
  id: string
  /**
   * 在哪一段**结束**的时候打出去（阶段 id）。
   *
   * ⚠ 为什么效果必须写清楚"什么时候发生"：技能是**时间轴**，
   *   "挥砍在起手结束之后发生"是它定义的一部分，不是附属信息。
   */
  at: string
  /** 这一下干了什么。可以是多件（"打穿并把人推走"） */
  then: Action[]
  /** 设计意图（和 `Rule.note` 同规矩：写给玩家看、不许写数字） */
  note?: string
}


// ============================================================================
//  七、阶段（时间轴）
// ============================================================================

/**
 * 一个施法阶段。
 * 前摇、释放、后摇、引导、蓄力 —— 全是它的实例。
 *
 * 关键字段 occupiesCaster：
 *   true  → 持续技（施法者被占用，效果随施法者存在，被打断就没了）
 *   false → 脱手技（效果放飞后独立存在，打断也拦不住已经飞出去的东西）
 */
export interface Phase {
  id: string
  name?: string
  /** 时长（秒）。蓄力阶段可以设 -1 表示由玩家控制 */
  duration: number
  /** 是否占用施法者（决定这是持续技还是脱手技） */
  occupiesCaster: boolean
  /**
   * 打断等级。**不是布尔值** —— 玩家要的是三档。
   *
   *   'damage'  被伤害打断（默认）—— 最脆。挨打就断。
   *   'control' 只被控制打断 —— 挨打不断，但被眩晕/沉默会断。
   *   'none'    无法打断 —— 霸体帧。名刀、大招的释放帧。
   *
   * 为什么必须分三档：只有"能/不能"两档的时候，一个"扛得住小伤害、
   * 但吃硬控"的释放帧表达不出来 —— 而那恰恰是动作游戏里最常见的那种帧。
   *
   * 定价见 src/pricing.ts：三档都是**收益**（消耗额度），
   * 'control' 算一半、'none' 算全额。
   */
  interrupt?: InterruptLevel
  /** 能否被玩家主动取消 */
  cancellable: boolean
  /** 这个阶段禁用施法者哪些能力（如锁定朝向 = 禁用 turn） */
  locks?: Capability[]
  /**
   * ⚠ **这一格不是技能写的，是修饰零件「等待 X 秒」插进来的空档**（2026-09-30 日志 52）。
   *
   * 为什么要有这个标记（而不是"看 id 前缀就知道了"）：
   *   · 定价要认出它 —— 等待的价走自己的汇率（`balance.json` 的
   *     `modifierRates.waitSecondPerPoint`），**不走** `Phase` 那套
   *     "时长 + 扛打断"的算法。两条路一起收就是**同一件事收两次钱**。
   *   · 它**只可能出现在编译产物里**（`CompiledTechnique.phases`）——
   *     内容层 `content/skills/*.json` 里写这个字段没有意义，
   *     因为内容里那一条时间轴是**技能自己的**，没有修饰零件插得进来。
   *
   * ⚠ 它**不是**"这个阶段很特殊"的开关，引擎读不读它都一样跑
   *   （等待就是一段普通的时长阶段，`locks` / `interrupt` 都照常生效）——
   *   唯一多出来的读者是定价器。
   */
  wait?: boolean
  /** 在这个阶段付出代价（代价时机是玩家的设计自由） */
  cost?: Cost
  /**
   * ⚠ 这里**没有** `points` 字段 —— 阶段的点数由时长、打断等级、
   *   以及上面 cost 里的能量/CD/生命推导出来。见 src/pricing.ts。
   */
}

/**
 * 打断等级。
 *
 * 越靠前 = 越容易被断 = 越安全（越弱），所以点数也越少。
 */
export type InterruptLevel =
  | 'damage'   // 被伤害打断
  | 'control'  // 只被控制打断（挨打不断，硬控能断）
  | 'none'     // 无法打断

/**
 * 代价。它可以挂在任意阶段上 —— 这是玩家自由的一部分。
 *
 * ## 挂在哪 = 什么时候开始算
 *
 * 代价在阶段**开始时**结算（`enterPhase` → `payPhaseCost`），而且**不退还**。
 * 所以挂在哪一个阶段，就是玩家在选"什么时候付"：
 *
 *   挂前摇 → 一按就进冷却。越靠前越先进 CD，但被打断就白付了（代价最大）。
 *   挂释放 → 打出去的那一刻进 CD。被打断在释放之前就不付。
 *   挂后摇 → 挥完了才进 CD。最安全，但也最晚。
 *
 * 编辑器把这件事做成一个显式的三选一（前摇 / 释放 / 后摇），
 * 而不是让玩家从字段位置去猜。
 *
 * ⚠ 定价提醒：
 *   能量是固定速率回复的 → 早付出是"纯风险"，应该给点数。
 *   CD 从进入时刻倒计时 → 早进 CD 自带收益（技能时长被算进冷却），
 *   不应该给点数，甚至应该扣。两者必须分开定价。
 */
export interface Cost {
  /** 能量消耗 */
  energy?: number
  /** 冷却秒数（同时决定这条代价的点数） */
  cooldown?: number
  /** 生命消耗 */
  hp?: number
  /** hp 是否按最大生命百分比计 */
  hpIsPercent?: boolean
  // ⚠ 这里原来有个手写的 `bloodPact?: number`，删了。
  //   血契**是算出来的**（`PriceResult.bloodPactPerUse` = 超模的那部分点数），
  //   手写一份是重复真相 —— 和第一版手写 `points` 是同一个错误，
  //   而且它零引用、零内容。见 schema/PLANNED.md。
}


// ============================================================================
//  八、目标
// ============================================================================

export interface Targeting {
  /** 怎么选中人 */
  mode: TargetingMode
  /**
   * 对谁有效。这是一层标签过滤，和"怎么选"是两件事。
   * 例如：用鼠标指向，但只对 enemy 有效 → mode: 'directional', valid: ['enemy']
   * 对本该无效的目标释放 → 释放成功但不产生效果（所以 UI 必须显示出来）
   */
  valid: string[]
  /** 最大距离（米） */
  range?: number
  /**
   * **只挑身上有这种标签的状态的目标**。
   *
   * ⚠ 玩家 2026-09-21 要的那个二段技能逼出来的（原话）：
   *   > 给最近的敌人挂上标记（不进入CD）、再次按下技能会瞬移到标记敌人身后（进入CD）。
   *
   *   第一段是"最近的敌人"（`mode: 'auto'` 就够），
   *   但第二段要的是"**我标过的那个人**" —— 而 `auto` 只会挑最近的。
   *   没有这一条的话，第二段打的是"现在最近的那个"，
   *   也就是"只要你稍微走位，瞬移就会打到别人身上"。
   *
   * ⚠ 它是**标签**（`StatusDef.tags`），不是状态 id：
   *   任何带这个标签的状态都算。所以以后"血怒标记""猎杀印记"
   *   只要带上 `marked`，同一个技能就能用它们。
   */
  requireStatusTag?: string
}


