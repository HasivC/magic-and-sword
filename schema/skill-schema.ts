//
//  玩家原话（2026-09-21）：
//    > 玩家应该有武器（暂时限于近战武器），可以使用挥砍、刺击等多种攻击方式
//    > （可以划归技能），武器可以铭刻技能来作为额外的技能，这个技能是和武器绑定的。
//
//  ⚠ **ComboChain 没有搬回来** —— 它被**序列层**取代了。
//    原来的设计是"轻击→轻击→重击 + 输入窗口 + 取消窗口"，
//    一堆时间数字写死在武器上；现在这些变成了
//    「术式的 `sequences` + `sequenceTimeout` + 阶段自己的取消规则」，
//    而且**玩家能自己编排**。所以它不需要单独一个类型了。

/**
 * 技能来源：技能栏**不止来自角色**。
 *
 * ⚠ 它解决的问题是"铭刻在武器上的术式属于武器，不属于角色"：
 *   换一把武器，那些术式跟着走 —— 而这个信息必须有地方存。
 *
 * 现在只有两种来源（角色 / 武器），但结构是"多个来源的聚合"：
 *   以后加饰品、天赋、临时 buff 不用改结构。
 */
export interface SkillSource {
  kind: 'character' | 'weapon' | 'trinket' | 'talent' | 'buff'
  /** 这个来源提供的术式槽。null = 空槽 */
  slots: (string | null)[]
  /** kind 是 'weapon' 时，指向哪个 WeaponDef */
  weaponId?: string
}

/**
 * 武器。
 *
 * ⚠ 一把武器只有**两个术式槽**（玩家 2026-09-21 定的）：
 *
 *   · `weaponTechnique` —— **武器术式**：就是左键那套普攻。
 *     它是一个写了 `sequences` 的术式（按一次走一条序列，到底回绕）。
 *   · `magicTechnique` —— **魔法术式**：一个**普通术式**，
 *     靠某个键触发，或者做成被动（被动不需要键）。
 *
 * ⚠ 武器技能的数值**不在技能里改**，而是由这里的属性**代入**：
 *   武器技能模板写 `ref: 'weapon.reach'`，同一份模板在不同武器上
 *   代入不同的值 —— 这就是玩家说的
 *   "每种武器的技能范围和伤害因为属性不同而不同"。
 */
export interface WeaponDef {
  schemaVersion: number
  id: string
  name: string
  note?: string
  /**
   * 武器属性。
   *
   * ⚠ 两个命名空间，**别混**：
   *   `weapon.*`  这把武器自己的参数（reach / damage / windup），
   *               **只**被武器技能的 `ref` 读
   *   `char.*`    给**持有者**的修饰（比如重剑让移速 ×0.9）——
   *               走的是和状态同一套修饰符系统，不新开机制
   *
   * ⚠ 缺项用 `WEAPON_DEFAULTS`（reach 2.5 / damage 1 / windup 1）。
   *   不这么做的话，忘写一个属性的武器会得到一把**打不到人**的剑。
   */
  attributes: Record<string, number>
  /** 武器术式（左键那套普攻）：一个写了 `sequences` 的术式 */
  weaponTechnique?: string
  /** 魔法术式：一个普通术式。靠键触发，或者做成被动 */
  magicTechnique?: string
  tags?: string[]
}

/**
 * 武器属性的缺省值**不在这里** —— 这个文件是**纯类型**的（一个值都不导出）。
 *
 * 表在 `technique-system/src/sim/types.ts` 的 `WEAPON_DEFAULTS`，
 * 和 `STORED_ATTRIBUTES` 放在一起：两者都是"引擎和内容共同约定的一张小表"。
 *
 * 缺省：`weapon.reach` 2.5 米 / `weapon.damage` 1 / `weapon.windup` 1。
 * 不这么做的话，忘写一个属性的武器会得到一把**打不到人**的剑。
 */


