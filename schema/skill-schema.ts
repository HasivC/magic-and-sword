// ============================================================================
//
//  ⚠ 这一节是**一片的一半**（2026-09-21，日志 48）：只做「数据形状 + 触发器 /
//    监测器 + 背水拆解」。
//
//  ⚠ 2026-09-21（日志 51）补上了**两个「份数」类动词**：「多重释放」（`multi`）
//    和「一分为 X」（`split`）。**「连锁」仍然不在这里**（它要"弹给最近的敌人"，
//    是另一个机制，不是份数）。
//
//  定稿：[`docs/sequence-and-modifier-model.md`](../docs/sequence-and-modifier-model.md) §八

/**
 * 一个修饰技能（修改器）**是什么机制**。
 *
 * ⚠ 玩家定的：修饰技能**不分类**（参数异构：位置 / 数量 / 时长 / 条件…），
 *   所以**不要**去搞一套统一的参数表。可"引擎要分成几等"这件事还是躲不掉 ——
 *   这个字段说的不是"玩法分类"，而是**引擎按哪套规矩执行它**：
 *
 * | kind | 引擎怎么执行 | 参数长什么样 |
 * | --- | --- | --- |
 * | `trigger` | 条件满足 → **激活它后面那个技能** | `params.when` + `params.condition` + `params.origin` |
 * | `monitor` | 同上，但条件是"**监测什么**"（血量低这类），每 tick 看一次 | 同上 |
 * | `wrap`    | **不是执行它，而是改它后面那一块的性质**（常驻包装） | 没有参数 |
 * | `multi`   | **一次激活里把它后面 N 个技能一起打出去**（多重释放） | `params.count` + `params.max` |
 * | `split`   | **把同一个技能变成 X 份**（一分为 X） | `params.count` + `params.max` |
 * | `wait`    | **在它后面那个技能前面插一段空档**（等待 X 秒） | `params.seconds` + `params.locks` + `params.interrupt` |
 *
 * ⚠⚠ **`wait` 的 `params.locks` 只剩 `move` / `turn` 两项**（2026-09-30 日志 54）：
 *   玩家定的硬规矩 —— **同一个施法者，同一时刻只能有一个"进行中的施法"**
 *   （原话："玩家又没有第二人格"）。它由**引擎**强制（`canActivate` 的
 *   `hasRunningCast` ⇒ 原因 `busy`），**和零件锁没锁它无关**；
 *   武器攻击也是绑在左键上的术式 ⇒ `attack` 被同一条硬规矩挡着。
 *   ⇒ 所以 `cast` / `attack` 写进修饰零件的 `locks` 会被校验器**报错**
 *     （`MODIFIER_LOCK_ENGINE_RESERVED`，说清"施法独占是引擎硬规矩，不是可配项"）。
 *   ⚠ `Capability` 那四个值本身**没变**：技能内容里的 `Phase.locks` 照样能写
 *     `cast`（那是**作者写在阶段上**的声明，报的是另一条 `locked`）。
 *
 * ⚠ 都在**同一个联合**里（`ModifierProto`），因为"一条序列里不叠同类"
 *   那条规矩要按 `kind` 去重 —— 分成几个类型的话，去重就得写几遍。
 *
 * ⚠ **`multi` 和 `split` 是两条不同的轴**（2026-09-21，日志 51）：
 *     · `multi` 动的是"**几个不同的技能**"（它后面 N 个**互不相同**的瞬发技能）
 *     · `split` 动的是"**同一个技能的份数**"（X 份，蓝耗按份数乘）
 *   所以它们在 `MODIFIER_STACKED_KIND` 那条规矩眼里是**两个类别**、
 *   可以同时出现在同一个技能前面 —— 两者叠加怎么算见日志 51 的裁定。
 *
 * ⚠ **`wait` 动的是第三条轴：时间**（2026-09-30，日志 52）——
 *   它不改份数、不改位置，只把**后面那一格往后推 X 秒**。
 *   落地方式是在编译期**往时间轴里插一个真阶段**（`Phase`，带 `wait: true`）——
 *   于是"施法者被占用 / 锁哪些能力 / 不可打断"这三件事**一行新引擎代码都不用写**：
 *   它们本来就是阶段的性质（`Phase.locks` / `Phase.interrupt`）。
 *
 * ⚠ **`layout` 动的是第四条轴：位置与方向**（2026-09-30，日志 53）——
 *   它**只管排布 / 路径**，⚠⚠ 两条硬界线：
 *     1. **不管份数**：份数归 `multi` / `split`（"一分为 X"）或者技能本来就几发。
 *        它只把**已经存在的那几份**摆到不同位置 / 方向。
 *     2. **不改瞄准**：意图照旧一个（`ActivateOptions.intent`）——
 *        它做的是"把同一个意图绕施法者转一个角度"。
 *   一个零件、**编辑时选类型**（`params.type`）：环绕 / 扇形散射 / 反向镜像。
 *
 * ⚠ **`homing` 动的是第五条轴：飞行路径**（2026-09-30，日志 56）——
 *   它让**被它修饰的投射物**在半路上**自己找最近的敌人、拐过去**
 *   （玩家原话："正常的技能只沿着发射方向走，而追踪技能**瞄准敌人**"；
 *   追问后确认："**自己找敌人**"）。
 *   ⚠⚠ 三条界线（玩家明确划的，违反就算做错）：
 *     1. **只对"会飞的东西"有效**（`delivery.kind === 'projectile'`）。
 *        `beam` / `capsule` / `meleeArc` / `aura` / `area` / `self` 这些**非飞行载体**
 *        被它修饰 ⇒ **什么都不做**（照「环绕」那条先例：不是警告、不是报错，
 *        而是"**这个修饰对这条序列不起作用**"，提示由界面画在那条序列下方）。
 *     2. **找不到敌人 ⇒ 沿原发射方向直走**（不许乱拐）—— 和"没目标就什么都不发生"同源。
 *     3. ⚠⚠ **它不改施法时的瞄准**（`CastInstance.facing` / 落点一个字节都不碰）：
 *        改的是**已经飞出去的那一发自己的速度方向**（`Entity.vel`）。
 *        ⇒ **"修饰不许碰瞄准"不是铁律**：「排布」那种**排布类**零件不许改意图
 *        （它只是把已有的那几份摆开），而追踪**确实换目标** —— 让**这一发**
 *        自己找敌人。两者不冲突，别把这一条读成违反了什么。
 *   ⚠ 转向**不用三角函数**（`src/sim/**` 的纯净性禁止 `sin` / `cos`）：
 *     走日志 53 加的**整圈角度表 + `rotate2()`**（`src/sim/targeting.ts`），
 *     而且只用白名单里的 `Math.sqrt` / `Math.sign` ⇒ **可重放**（无随机、无浮点漂移）。
 */
export type ModifierKind =
  | 'trigger'
  | 'monitor'
  | 'wrap'
  | 'multi'
  | 'split'
  | 'wait'
  | 'layout'
  | 'homing'
  /**
   * ⚠ **`bounce` 动的是第六条轴：命中之后的去向**（2026-09-30，日志 58）——
   *   被它修饰的**投射物命中一个敌人之后**，**弹给最近的另一个敌人**，
   *   最多 N 次，每次衰减（玩家原话："**弹两下的闪电**"）。
   *
   *   ⚠⚠ 四条界线（玩家明确划的，违反就算做错）：
   *     1. **只对"会飞的东西"有效**；非飞行载体（激光 / 光束 / 扇形 / 光环 /
   *        落点区域 / 自己）⇒ **什么都不做**、**而且不收费** ——
   *        ⚠ 这**和 `homing` 是同一条规矩**，所以判据**共用**一个函数
   *        （`src/school.ts` 的 `carrierFliesInWorld`，原来叫 `homingAppliesTo`）。
   *     2. **不许弹回刚打过的那个**（否则来回弹）；**没有别的敌人时停下**、不弹
   *        —— 和"没目标就什么都不发生"同源。
   *     3. ⚠⚠ **它的次数上限和 `pipeline` 的深度限制是同一个数**
   *        （`src/limits.ts` 的 `MAX_ACTION_DEPTH`，现在是 4）：
   *        弹射是一条链，链上每一段都是**一颗新子弹**（`sim/projectile.ts` 的
   *        `bounceToNextTarget`）⇒ `executeAction` 的 `depth` **不会自然累加**
   *        ⇒ 那个数是这条链**唯一**的刹车。玩家原话：
   *        "各写一份迟早出现**弹射绕过深度保护 ⇒ 自反馈**"。
   *     4. **它只动"这一发接下来去哪"**：施法时的瞄准（`CastInstance.facing` /
   *        落点）一个字节都不碰，和 `homing` 同一条（见上面那一段）。
   *
   *   ⚠ `homing` 是"这一发自己拐过去打**同一个**目标"，`bounce` 是"打完一个
   *     **再换一个**目标" —— 两个零件**可以同时装**：弹射过去的每一段照样会拐。
   */
  | 'bounce'

/**
 * 「等待 X 秒」这一段空档**能不能被打断**（默认 `'none'`）。
 *
 * ⚠ **它和 `InterruptLevel` 是同一个三档**（故意**不新造一套取值**）——
 *   落地时直接写进那个等待阶段的 `Phase.interrupt`，所以这里多一个取值，
 *   引擎那边就多一条**它今天本来就会执行**的分支，不需要任何转换层。
 *
 * ⚠ 默认取 `'none'`（玩家定的，原话："我觉得默认不可打断更合适"），
 *   理由写在 `content/modifiers/wait.json` 的 `_comment` 里（那一段是定稿口径）：
 *   可打断会让"晚 X 秒"当场消失，而后面那个技能反而**提前**打出来 ——
 *   那不是打断，是把排好的序列顺序改掉了。
 *   ⇒ 它是**参数的默认值**，玩家要"能被打断的等待"就显式改成 `'damage'` / `'control'`。
 */
export type ModifierWaitInterrupt = InterruptLevel

/**
 * 被触发的那个技能**在哪儿生成**（四选一，玩家定的）。
 *
 * ⚠ 名字里的 `prev` 是"**触发它的那个技能**"（定稿 §八 的原话）——
 *   而今天真正触发的是**修饰技能自己所在的那一条规则**（见 `SegmentMod`）。
 *   所以后两项读的是"上一次触发留下的那个点"（见 `TriggeredFire`）。
 *   ⚠ 语义上的含糊之处**写在欠账里**（报告第 5 节），没有自己定下来。
 *
 * ⚠⚠ **`aim` 那一档 2026-09-30（日志 62）换了口径**（玩家选的「丙」）：
 *   取的是「**触发这个技能的那次施法**在按下那一刻解算出来的意图」（落点 / 方向），
 *   **不是**实时的鼠标位置，**也不是**旧口径那个"最近的敌人"（日志 48 ~ 61 的退化）。
 *   ⚠ **取不到就什么都不做**（和"没目标就不发生"同一条纪律）——
 *   只有「载体消失」（`onExpire`）那条路手里有那次施法；监测器 / 挂载那几条路没有。
 */
export type TriggerOrigin =
  /** 1. 施法者身上 */
  | 'caster'
  /** 2. **触发这个技能的那次施法**的瞄准（落点 / 方向）—— 取不到 ⇒ 这一档什么都不做（日志 62） */
  | 'aim'
  /** 3. 触发它的那个技能的**命中位置** */
  | 'prevHitPoint'
  /** 4. **失效位置** ⚠ 这一项的确切含义还没定（定稿 §八 / §十三 欠账） */
  | 'prevEndPoint'

/**
 * 修饰技能的**原型**（出厂零件）。
 *
 * ⚠ **原型住内容层**（`content/modifiers/*.json`）：只读、出厂、**玩家不能创建原型**
 *   （玩家 2026-09-21 定的）—— 拖进序列得到的是**副本**（见 `SegmentMod`）。
 *
 * ⚠ **它没有 `points` 字段，也不是 `Skill`**：
 *   · 修饰技能的点数怎么算**玩家还没给规则**（日志 48 的欠账）——
 *     所以这一片**照今天的账走**、不给它造点数，绝不自作主张定一个。
 *   · 它不是 `Skill`：`Skill` 讲"前摇 / 命中 / 后摇"（一次释放的时间轴），
 *     修饰技能讲的是"**一条改写规则**"——定稿 §八 明说了编辑界面是两套。
 *     ⇒ 它**进不了技能库、也不占技能的点数账**（怎么算待裁定）。
 */
export interface ModifierProto {
  schemaVersion: number
  id: string
  name: string
  /** 给玩家看的一句话。和 `Skill.note` 同规矩：**不许写数字** */
  note?: string
  kind: ModifierKind
  paramsTemplate?: Record<string, unknown>
  /**
   * 引擎要额外读的**固定参数**（原型自己写死，副本不能改）。
   *
   * ⚠ 为什么参数既要 `paramsTemplate` 又要 `params`：
   *   · `paramsTemplate` 是**给编辑器和人看的形状**（"这个零件有哪些旋钮、
   *     默认值是什么"）—— 它进不了引擎逻辑；
   *   · `params` 是**引擎真的读的那几个值**，而它写死在@原型上 ——
   *     因为这一片**还没有编辑界面**（编辑器是下一片），副本的 `params`
   *     由"原型默认值"填出来。
   *   ⚠ 两份会漂移 —— 所以原型加载时校验器盯着"引擎读的那几个键在不在"
   *     （`MODIFIER_PROTO_BAD_PARAMS`），而不是靠人自觉。
   */
  params?: Record<string, unknown>
  tags?: string[]
}

/** `wrap` 能改的那一条性质。今天只有一种 */
export type WrapEffect =
  /** 把**它自己和它后面那个技能**包装成常驻（进常驻序列、不参与按键激活） */
  | 'persistent'

/**
 * 一条**修饰副本**：挂在某条序列上、修饰它后面第 `at` 个技能。
 *
 * ⚠ 为什么 `mods` 不塞进 `skills: string[]`（玩家点名的红线）：
 *   技能表是"这一段按顺序执行哪几个技能"，插进去一个不是技能的东西
 *   会把上一片（序列内联 / 瞄准搬家）的成果全部推翻 ——
 *   每一处 `skills` 的读者都得重新判"这个字符串是不是技能"。
 *   ⇒ 副本**并列**在 `mods` 里，用 `at` 表达位置。
 */
export interface SegmentMod {
  /** 引用一个原型（`content/modifiers/*.json` 的 id） */
  proto: string
  /**
   * 它修饰**它后面第几个技能**（0 = 紧邻的下一个）。
   *
   * ⚠ 用**序号**表达位置，而不是"插在数组的哪一格"：
   *   数组那一格是**修饰自己的家**（一条序列里可能有好几个副本），
   *   而"修饰谁"是另一个事实。两件事混成一个下标的话，
   *   挪动一个副本会静默地把它的目标换成另一个技能。
   */
  at: number
  /**
   * 这次的参数值（= **触发条件** + **生成位置四选一**）。
   *
   * ⚠ 用**现成的事件清单**（`TriggerEvent`）当条件来源 —— 玩家明说了
   *   **不要新造事件**。所以 `params.when` 只允许 `TriggerEvent` 里已有的值。
   */
  params: Record<string, unknown>
}

/**
 * `Technique.sequences` 的取值。
 *
 * ⚠ **两半都要认**，这不是防御性编程：
 *   · `SequenceSegment[]` —— 内联（模型 B，现在写内容用这个）
 *   · `string[]`         —— 老形状（引用另一份术式）。**老存档和老分享码里就是它**
 *     （玩家 2026-09-21：分享码是别人手里存下来的东西，判死就是垃圾）。
 *
 * ⚠ 别在别处也开一个这样的联合：判据多了就会漂移成两套规矩。
 *   归一化只在一处：`src/school.ts` 的 `segmentSkillsOf()`。
 */
export type TechniqueSequences = (string | SequenceSegment)[]

/**
 * 术式：**绑定到按键的东西**。释放的是它。
 *
 * 术式 = 若干技能 + 它们之间的连接条件。
 * 这就是"给技能编程"的地方 —— 位移、判定、触发、收招，
 * 各是一个技能，由术式把它们连成一个能用的招式。
 *
 * 只包含单个技能的术式是最常见的情况，但那是它的特例，不是它的定义。
 */
export interface Technique {
  schemaVersion: number
  id: string
  name: string
  note?: string
  /**
   * ---- **系别**：这是一门武器术式还是一门魔法术式。**必填，而且必须显式写。** ----
   *
   * ⚠ **为什么不能靠"有没有 `sequences`"推**（这是它存在的**全部理由**）：
   *   今天"武器术式"的判据就是"它写了 `sequences`"（见上面三层模型）。
   *   可是序列层**已经不是武器专用**的了 ——「标记 · 瞬影」就是拿序列做的
   *   二段技能（玩家 2026-09-21：「序列机制……现在我觉得也应该作用于魔法技能了，
   *   因为想实现二段技能只能用这种方法」）。而**新编辑器会让所有术式都走序列层**
   *   （技能之间怎么接、每一段自己的 CD，全用序列表达）。
   *   到那时候"有序列 = 武器术式"当场失效 —— 而且失效得**非常安静**：
   *   一门魔法术式会被当成武器术式（不给它算账、编辑器的技能库只给它武器模板），
   *   没有任何一处会报错。所以这个判据必须在它失效**之前**就变成显式字段。
   *
   * ⚠ 另一侧是**不对称**的，别搞混：**技能的系别不是字段，是目录**
   *   （`content/skills` = 魔法系、`content/weapon-skills` = 武器系，
   *   见 `Skill.school` 和 `src/school.ts`）。因为"这个技能是从哪儿来的"
   *   有目录这个看得见的事实；而"这门术式要造什么"**只有玩家知道** ——
   *   所以术式这一侧必须写出来。
   *
   * ⚠ **新建时由玩家选，之后不能改。**
   *   编辑器的**技能库按它过滤**（武器术式只列武器技能模板、魔法术式只列技能库），
   *   所以它得在一份术式**存下来之前**就定好。允许事后改的话，
   *   "改一下系别"会把里面已经引用的技能**全部变成非法**
   *   （校验器的 `WEAPON_TECHNIQUE_MAGIC_SKILL` / `MAGIC_TECHNIQUE_WEAPON_SKILL`
   *   就是那条规矩）。要换系别就新建一份。
   *
   * ⚠ 老内容 / 老存档没有它的，由加载器按一条**传递**的规则补上：
   *   **直接、或顺着 `sequences`（可能多级）引用了武器系技能 → `weapon`，否则 `magic`**。
   *   ⚠ **不是**"有 `sequences` 就是 weapon" —— 那一句 2026-09-21 被玩家当场证伪
   *   （「标记 · 瞬影」是拿序列层做的**二段魔法技能**，它一个武器技能都没引用）。
   *   见 `src/school.ts` 的 `deriveTechniqueKind`。
   */
  kind: SkillSchool
  activation: ActivationMode
  /*
   * ⚠ 这里原来有个 `targeting: Targeting`（**必填**，术式自己的瞄准）。
   *
   *   **2026-09-21（日志 47）删掉了** —— 玩家定的：**术式没有瞄准，瞄准在技能上**
   *   （每个技能各自解释那**一个意图**，见 `Skill.targeting`）。
   *   定稿见 [`docs/sequence-and-modifier-model.md`](../docs/sequence-and-modifier-model.md) §六 / §九。
   *
   *   ⚠ 这次搬家**行为逐位不变**：出厂内容里每个技能都显式写上了
   *     "它今天实际生效的那份瞄准"（原来挂在它所在的术式 / 序列段上），
   *     而编译产物那份 `targeting` 现在是从**技能**身上取来的
   *     （`technique-system/src/sim/compile.ts` 的 `targetingOfChain`）——
   *     所以 `resolveAim` / 动作默认目标 / AI 挑术式**一行都没改**。
   *
   *   ⚠ 老存档 / 老分享码里的术式**仍然读得进来**：多余的字段被忽略，
   *     瞄准由它引用的技能提供（那批技能今天也都带着自己的瞄准）。
   *
   *   ⚠ 别把它加回来：校验器对着术式里写回去的 `targeting` 报
   *     `TARGETING_MOVED_TO_SKILL` ✗（防回潮）。
   */
  /**
   * 按顺序执行的技能 id。
   *
   * ⚠ **序列术式不写它**（`skills` 和 `sequences` 二选一），
   *   所以这里是可选的 —— 武器术式基本上都是这种。
   *   读的时候一律 `tech.skills ?? []`：`tech.skills.length` 这种写法
   *   在序列术式上会直接炸（而且是"内容一加载就炸"，不是按下去才炸）。
   */
  skills?: string[]
  /**
   * 技能之间的连接条件。长度应为 `skills.length - 1`。
   *
   * ⚠ 这个字段是"术式能编程"的关键。少了它，`skills` 只是一条
   *   无条件执行的流水线，"碰到了才触发"这类写法就无处可写。
   */
  links?: SkillLink[]
  /**
   * ---- **序列层**（武器术式用它）----
   *
   * ⚠ 玩家 2026-09-21 的原话：
   *   > 本质上是在术式的层级之下多加了一层序列层，用来实现每次攻击的效果有差异。
   *   > 序列在**实现方式**上可以看作术式，但在**激活方式**上它在术式层级的下方。
   *
   * 所以模型是三层，和"术式编排技能"是对称的：
   *
   * ```
   * 技能 Skill        零件
   *   ↑ 被序列编排
   * 序列 Sequence     一层编排：**若干技能** + 它们之间的条件门
   *   ↑ 被术式编排
   * 术式 Technique    绑输入的东西
   * ```
   *
   * 激活方式完全不同：
   *   · **普通术式**：按一次 → 把 `skills` 从头走完 → 结束
   *   · **武器术式**（写了 `sequences`）：按一次 → 走**一条序列** →
   *     再按一次走**下一条** → 到底回绕（`sequenceTimeout` 内没按就回第一条）
   *
   * ⚠ `skills` 和 `sequences` **二选一**（校验器盯着）。同时写的话
   *   "按一次到底该走哪套"没有答案。
   *
   * ## ⚠ 2026-09-21：序列**内联**了（模型 B）
   *
   * 以前这里是 `string[]` —— 每条序列**引用另一份术式**（`tech.ws-slash`），
   * 而那几份子术式在内容里各占一个文件。代价是"二段技能"要多出四份
   * 只有引擎看得见、编辑器完全编不出来的文件（见 `docs/sequence-model-plan.md`）。
   *
   * 现在序列**自己带技能列表**（`SequenceSegment[]`），子术式那几份文件删掉了。
   * 编译器把每条序列合成为一份**内部术式**（id 见 `SequenceSegment.id`），
   * 后面的东西（`activate` / `canActivate` / 冷却键 / HUD 的 `cd.*` / 链状态）
   * 一行都不用改 —— 它们本来就只认"一份编译好的术式"。
   *
   * ⚠ **字符串数组仍然读得进来**（`TechniqueSequences` 那个联合类型的另一半）：
   *   老存档和老分享码里就是那个形状，判死等于玩家手里的东西全成垃圾。
   *   见 [`docs/log/2026-09-27-46-inline-sequences.md`](../docs/log/2026-09-27-46-inline-sequences.md)。
   */
  sequences?: TechniqueSequences
  /**
   * 序列之间的条件（和 `links` 一样是**平行数组**：`sequenceLinks[i]` 管 `sequences[i+1]`）。
   *
   * ⚠ 玩家 2026-09-21 明确要了这个："序列之间也能带条件"。
   *   所以"第一段打中了才接第二段"这类写法在**序列之间也能写**，
   *   不必把它塞进某一条序列内部。
   */
  sequenceLinks?: SkillLink[]
  /**
   * 两条序列之间**最多隔多久**（秒）还算连着。
   *
   * 超了就从第一条重新开始 —— 否则"停一下再按"会从中间接上，
   * 玩家会觉得莫名其妙。默认 1 秒。
   */
  sequenceTimeout?: number
  /*
   * ⚠ 这里原来有个 `skillCopies?: Skill[]`（"每个术式各存一份技能快照"）。
   *
   *   它**删掉了**，因为那个模型是错的 —— 玩家 2026-09-21 纠正过：
   *   > 技能是玩家拥有的东西……**自定义技能是独立的，它不属于术式**。
   *
   *   私藏在术式里的副本有三个说不通的地方：
   *     · 技能不是"你拥有的东西"，只是一个术式的内部字段（列不出来、取不了名字）
   *     · 同一个技能在 N 份术式里是 N 份互不相干的副本，改一份不影响另一份 ——
   *       而玩家要的是"改它，**所有用到它的术式**都跟着变"
   *     · 删掉一份术式会把它里面的技能改动一起带走
   *
   *   现在改成：**两个库**（基础技能库 + 存档里的自定义技能库）+
   *   `Skill.basedOn`（账的基准）。查找技能只有一句：**自定义库优先、基础库兜底**。
   */
  /*
   * ⚠ 这里**曾经**有个 `modifierCopies?: SegmentMod[]` —— 2026-09-21（日志 48 收尾）
   *   **删掉了**，玩家裁定："**真相是 `sequences[].mods`**，不要另存一份"。
   *
   *   它和上面那个 `skillCopies` 是**同一个错**：为了"好查"再存一份摊平表。
   *   而"好查"的代价是**必须有人保证两份一样** —— 那个"有人"不存在，
   *   所以两份迟早不同步（而不同步的表现是静默的：列出清单用的是一份、
   *   引擎执行用的是另一份）。
   *
   *   ⚠ 副本住在 `sequences[].mods` 里（玩家定的形状），**它自己就是那份副本**；
   *     将来说"列出这份术式用了哪些修饰"，那是**从 `sequences[].mods` 推出来的**
   *     （一个纯函数，不落库），**不需要另存一份**。
   *
   *   ⚠ 删它**零行为改动**：它从来没有被写过（全仓一处赋值都没有），
   *     校验器也不查它。`web/src/store.ts` 里那句恒为假的防御性拷贝跟着删了。
   */
  tags?: string[]
}

