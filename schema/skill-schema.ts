// ============================================================================
//  术式系统 Schema v1
// ============================================================================
//
//  命名约定
//    · 类型 PascalCase，字段 camelCase，枚举值小驼峰
//    · 事件统一 onXxx
//    · 属性用点分路径字符串：'char.critRate' / 'skill.cooldown'
//
//  核心比喻
//    术式 = **若干技能用条件连起来的程序**
//    技能 = 一段带阶段和规则的东西（会位移、会打人、会挂状态）
//    规则 = 当【时机】若【条件】则【动作】
//    动作 = 载体 + 载荷
//
//  ⚠ **宗旨**（玩家 2026-09-21 定的，见 README 第五节）：
//    > 所有点数相关的可调整的值，都具有一个默认值，在这个默认值下点数是配平为0的。
//
//    也就是说：出厂内容**天然是配平的**，编辑器里的每个滑块都是
//    "从默认值出发做交易" —— 往强了拖要补代价，往弱了拖会提供额度。
//    ⚠ 给某个值定价之前，先回答"它的默认值（= 0 点）是多少"。
//      回答不出来，说明它多半不该进点数账。
//
//  ⚠ **参考的是 Noita 的法杖编程玩法**（玩家 2026-09-21 指明的）：
//      本游戏的**技能** ↔ Noita 的**魔法（spell）**
//      本游戏的**术式** ↔ **一把法杖里的全部魔法**（含施法顺序、施法块、充能）
//    ⚠ 所以"术式/技能"这两个词的边界要按 Noita 那套去想，
//      而不是按"技能=一招、术式=连招"的直觉。
//
//  ⚠ 两层模型（**释放的是术式，修改的是技能**）
//
//    技能 Skill           零件。有阶段、有规则、有代价。**玩家编辑的是它。**
//       ↓ 被 `skills` 引用，被 `links` 连起来
//    术式 Technique       编排。**释放的是它。** 它不只是"一串技能"——
//                        技能之间可以带条件（`links`），
//                        所以"位移过去，碰到了才炸"是**术式层**写的。
//       ↓ 编译（core-sim/compile.ts）
//    CompiledTechnique    一条接起来的时间轴 + 每段的进入条件。**引擎唯一认的形态。**
//
//  ⚠ **没有"组合技"这个概念。**
//     曾经有过一个 `Combo` 类型（"可分享的技能组 ≈ 函数"），已经删掉了：
//     分享码是**术式**的东西，不是另一个概念。
//
//  ⚠ 本文件只声明"数据长什么样"，不含任何执行逻辑，也不含**价格**。
//     执行逻辑属于 core-sim，它必须不引用任何外部 API（见 README 纪律 4）。
//     价格（点数）由内容推导，见 technique-system/src/pricing.ts。
// ============================================================================


// ============================================================================
//  一、基础枚举
// ============================================================================

/** 激活方式：玩家怎么"按"出这个术式 */
export type ActivationMode =
  | 'press'    // 按下瞬间触发一次
  | 'release'  // 按下开始蓄力，抬起时释放
  | 'hold'     // 按住持续生效
  | 'toggle'   // 按下切换开 / 关
  | 'auto'     // 无需输入，常驻生效（纯被动）

/**
 * **施法形态**：这次释放**要不要一条时间轴**、要多长（见
 * [`docs/sequence-and-modifier-model.md`](../docs/sequence-and-modifier-model.md) §二）。
 *
 * | 形态 | 机制特征 | 内容里的例子 |
 * | --- | --- | --- |
 * | `instant` 瞬发 | 有时间轴，跑完就结束 | 横砍、魔法飞弹、裂地斩、瞬影 |
 * | `charged` 蓄力 | 时间轴里有一段**由玩家控制时长**（`duration: -1`） | 贯日 |
 * | `sustained` 持续 | 时间轴一直挂着，直到输入说"结束" | 引导光束、光环、火焰喷射 |
 * | `passive` 常驻 | **没有时间轴**，装上就生效（靠事件或每 tick） | 无下限、血契、猎手直觉、背水 |
 *
 * ⚠ **形态是"相对施法者"而言的**（玩家 2026-09-21 的原话）。所以"放一个图腾 / 召唤物"
 *   是**瞬发** —— 放下去那一下有完整时间轴 ✓；图腾之后怎么活着是**它自己的事**，
 *   不是这个技能的形态。同一个技能只能有一个形态：既被动又主动的东西**拆成两个技能**。
 *
 * ⚠ **默认是 `instant`（瞬发）**，理由有两条：
 *   1. **宗旨**（见文件头）：所有可调值都有一个"默认值下点数是配平为 0"的默认值 ——
 *      形态的默认值就是**最低介入的那一种**：出厂内容里绝大多数技能都是瞬发，
 *      不写就是它，作者不用为常见情况付一行字。
 *   2. **猜的面越小越好**：只有**不是瞬发**的那几个技能显式标出来，形态才是可核对的
 *      一张小表（今天的真实数字：6 个 `passive` + 1 个 `charged`）。
 *      日志 44 里"猜 kind"把「标记 · 瞬影」猜错的教训就在眼前 ✗ ——
 *      默认值一旦填成"看起来更聪明"的那一种，猜错是**静默**的。
 *
 * ⚠ **它和"激活方式"是两个概念，别混**（这是本节存在的全部理由）：
 *
 * | | 回答什么 | 住在哪一层 |
 * | --- | --- | --- |
 * | **激活方式** `Technique.activation` | 玩家**怎么按** | **术式层** |
 * | **施法形态** `Skill.form`（这个） | 这次释放**要不要一条时间轴**、要多长 | **技能层** |
 *
 *   所以两者要**对得上**：术式的激活方式决定了它能带动哪些形态的序列
 *   （相容表见 `src/validator/index.ts` 的 `FORM_ACTIVATIONS`，校验器报
 *   `FORM_INCOMPATIBLE`）。把形态写在技能上、激活方式写在术式上，
 *   "被动 + 法球塞进同一个术式"这种组合就**在数据上说不出来** ——
 *   而不是等它在运行时出错。
 */
export type SkillForm =
  | 'instant'    // 瞬发（默认）
  | 'charged'    // 蓄力：时间轴里有一段由玩家控制时长
  | 'sustained'  // 持续：时间轴一直挂着，直到输入说结束
  | 'passive'    // 常驻：没有时间轴，装上就生效

/** 触发时机：效果在什么时候发生 */
export type TriggerEvent =
  // 施法与命中
  | 'onCast' | 'onHit' | 'onMiss' | 'onCrit' | 'onNonCrit' | 'onKill'
  // 生命周期
  | 'onExpire' | 'onRemoved'
  // 空间
  | 'onEnter' | 'onLeave'
  // 受击
  | 'onDamaged' | 'onLethalDamage'
  /**
   * 身上**新挂上**一个状态。
   *
   * ⚠ 存在的理由是**血契**：玩家 2026-09-21 把血契的来源抽象成
   *   "让玩家进入危机的行为"，其中一条就是"获得了某个负面 buff"。
   *   没有这个时机的话，"被挂上诅咒就攒一点血契"写不出来。
   *
   * ⚠ 只在状态**第一次挂上**时触发，刷新时长和叠层**不触发**。
   *   两者都触发的话，一个每秒重挂一次的 debuff 会变成血契刷子 ——
   *   而"进入危机"该是一件有次数的事。
   *
   * ⚠ 触发时状态**已经挂上了**，所以规则里可以直接用 `hasStatusTag`
   *   判断刚挂上的是什么（见 conditions.ts）。
   */
  | 'onStatusApplied'
  // 其他
  | 'onLowHp'
  // 周期：用于持续效果，如"每 0.5 秒扣 3 能量"
  | 'onTick'
  // 阶段事件（配合 Rule.phaseId 使用）
  | 'phaseEnter' | 'phaseComplete' | 'phaseInterrupt'

/** 实体能力。所有"控制效果"都是禁用这些的某种组合 */
export type Capability = 'move' | 'attack' | 'cast' | 'turn'

/**
 * 伤害管线的六个步骤。顺序固定，永不由玩家改。
 * 玩家只能决定"同一个步骤内，谁的规则先执行"。
 */
export type PipelineStage =
  | 'raw'        // 1 原始：计算基础值
  | 'intercept'  // 2 拦截：名刀、免疫（阻止它发生）
  | 'modify'     // 3 修正：增减伤、伤害转治疗、亡灵反转
  | 'absorb'     // 4 吸收：护盾、次数盾
  | 'apply'      // 5 应用：真正扣血
  | 'after'      // 6 后置：吸血、反伤、onDamaged

/** 载体：效果怎么送出去（8 种） */
export type DeliveryKind =
  | 'self'        // 直接作用于自己
  | 'projectile'  // 飞行实体
  | 'beam'        // 瞬时或持续的直线
  | 'meleeArc'    // 近身扇形（挥砍）
  | 'capsule'     // 窄长直线（突刺）
  | 'area'        // 固定在空间
  | 'aura'        // 跟随施法者
  | 'spawn'       // 造出一个实体

/**
 * **技能系别**：武器系 / 魔法系。
 *
 * ⚠ 它不是 JSON 字段，而是**加载时按目录盖上去的派生章** ——
 *   理由写在 `Skill.school`（技能这一侧）和 `Technique.kind`（术式那一侧）里，
 *   推导规则只在一个地方：`technique-system/src/school.ts`。
 */
export type SkillSchool = 'weapon' | 'magic'

/** 目标选择方式：怎么选中人 */
export type TargetingMode =
  | 'self'        // 自己
  | 'directional' // 朝鼠标/朝向
  | 'locked'      // 锁定目标
  | 'auto'        // 自动（最近）
  | 'areapoint'   // 指定地面点

/** 属性修饰的操作 */
export type ModifierOp = 'add' | 'mul' | 'set' | 'reset' | 'stack'

/** 运行时量：动态参数可以引用这些 */
export type ValueRef =
  | 'distance'     // 到目标的距离
  | 'selfHpPct'    // 自己当前血量百分比
  | 'targetStacks' // 目标身上某状态的层数
  | 'targetCount'  // 范围内的目标数量
  | 'elapsed'      // 已持续时间
  | 'charge'       // 蓄力量
  | 'missingHpPct' // 已损失血量百分比
  /*
   * ---- 武器参数（**只有武器技能用得上**）----
   *
   * ⚠ 它们是"**这把武器**的数值"，不是持有者的属性。
   *   所以命名空间是 `weapon.*` 而不是 `char.*` —— 后者是**人**的属性
   *   （血量上限、移速…），混进去会分不清"这把剑更长"和"这个人跑得更快"。
   *
   * 武器技能模板里写 `ref: 'weapon.reach'`，同一份模板在不同武器上
   * 代入不同的值 —— 这就是"每种武器的技能范围和伤害因属性不同而不同"。
   *
   * ⚠ 缺项时用 `WEAPON_DEFAULTS`（见 WeaponDef 的注释），
   *   否则忘写一个属性的武器会得到一把打不到的剑。
   */
  | 'weapon.reach'   // 打得到多远（米）—— 扇形半径 / 光束长度 / 突刺长度读它
  | 'weapon.damage'  // 伤害倍率（×），1 = 基准
  | 'weapon.windup'  // 前后摇倍率（×），1 = 基准；攻速就体现在这里


// ============================================================================
//  二、值（常量或动态参数）
// ============================================================================

/**
 * 一个数值。可以是常量，也可以引用运行时量并走一条曲线。
 *
 * 这是"无下限术式"（越近越慢）能实现的原因：
 *   { ref: 'distance', curve: [[0, 1.0], [3, 0.3], [6, 0]] }
 *   含义：距离 0 米时效果 100%，3 米时 30%，6 米时 0。
 */
export interface ValueSpec {
  /** 常量值。与 ref 二选一 */
  const?: number
  /** 运行时量。与 const 二选一 */
  ref?: ValueRef
  /** 曲线：[[输入, 输出], ...]，线性插值。仅 ref 时有效 */
  curve?: [number, number][]
  /** 引用带标签时的过滤条件，例如引用"灼烧"层数 */
  refArg?: string
  min?: number
  max?: number
}


// ============================================================================
//  三、条件
// ============================================================================

export type ConditionType =
  | 'hasTag'        // 目标**自身**带某标签（undead / boss / construct）
  | 'hasStatusTag'  // 目标**身上的状态**带某标签（shield / dot / buff）
  | 'hasStatus'     // 目标身上有某状态（按 id 精确匹配）
  | 'stackAtLeast'  // 某状态层数 >= N
  | 'hpBelow'       // 血量低于 N%
  | 'distanceIs'    // 距离在区间内
  | 'targetCountIs' // 目标数量在区间内
  | 'isCrit'        // 本次是否暴击
  | 'hitKindIs'     // 本次命中是 damage 还是 heal（亡灵反转靠它）
  | 'prevHit'       // **上一段技能**有没有作用到任何人（技能链之间的条件）
  | 'not'           // 取反
  | 'anyOf'         // 任一成立
  | 'allOf'         // 全部成立

export interface Condition {
  type: ConditionType
  /** 判断谁：自己 / 本次目标 / 施法者 */
  who?: 'self' | 'target' | 'caster'
  /** 主参数：标签名、状态 id、数值阈值等 */
  value?: string | number
  /** 区间条件用 */
  range?: [number, number]
  /** not / anyOf / allOf 的子条件 */
  of?: Condition[]
}


