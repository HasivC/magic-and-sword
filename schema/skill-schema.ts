/**
 * 实体定义（玩家、敌人、召唤物共用）。
 *
 * ⚠ 它是 `spawn` 载荷唯一能引用的东西 —— 见 `SpawnPayload.entityId`。
 *   在实现 spawn 之前这个类型**一直是零引用的**：
 *   声明在这儿、校验器认它、`describe.ts` 会说"生成 entity.skeleton"，
 *   但没有任何代码读它（因为 spawn 会 throw）。这一轮才真的接上。
 */
/**
 * 一个实体的**形状**。
 *
 * ⚠ 现在只有两种，而且都不是"随便画"：
 *   `circle`   —— 人、柱子、力场。判定用"圆心到它的距离"。
 *   `segment`  —— **一堵墙**。判定用"它到线段的距离"（和载体的 capsule 同一套数学）。
 *
 * ⚠ 圆形做不出墙：一排圆之间一定有缝，子弹会从缝里穿过去，
 *   而那看起来像"墙漏了" —— 作者会以为是判定写错了。
 */
export type EntityShape =
  | { kind: 'circle'; radius: number }
  /** 以实体**朝向**为轴的一条线：长 `length`、宽 `width`，中心在实体位置 */
  | { kind: 'segment'; length: number; width: number }

/**
 * 屏障的**通行策略**：谁能穿过去。
 *
 * ⚠ 四项都是"**能穿**"（`true` = 放行），默认值是：
 *   自己的子弹放行、敌人的子弹挡住、人不挡。
 */
export interface BlockPolicy {
  /** 同阵营的子弹能不能穿过去 */
  ownProjectiles?: boolean
  /** 敌对阵营的子弹能不能穿过去 */
  enemyProjectiles?: boolean
  /** 同阵营的单位能不能穿过去 */
  ownUnits?: boolean
  /** 敌对阵营的单位能不能穿过去 */
  enemyUnits?: boolean
}

/**
 * 实体预设：可召唤单位的模板。
 *
 * ⚠ 里面的字段**引擎都真的读**（玩家 2026-09-21 的原则：
 *   > 改变它不会改变效果的东西，就不该进编辑器）。
 */
export interface EntityDef {
  schemaVersion: number
  id: string
  name: string
  /** 类别标签。被技能的 Targeting.valid 匹配：undead / boss / construct ... */
  tags: string[]
  /**
   * 归属。魅惑就是改这个字段。
   *
   * ⚠ 召唤物多数该写 `'caster'` —— 意思是"跟召唤它的人同一阵营"。
   *   写死 'enemy' 的话，敌人召唤出来的骷髅会帮着玩家打；写死 'player'
   *   反过来，玩家召唤的东西会打自己。
   *   这就是纪律 1（一切按阵营动态查询）在内容层的体现。
   */
  faction: 'caster' | 'player' | 'enemy' | 'neutral'
  /** 初始属性。路径 → 数值 */
  attributes: Record<string, number>
  /**
   * 这是个**什么东西**。不写就是 `'actor'`（会动、会打、有 AI 的那种）。
   *
   * ⚠ `'area'` 是 2026-09-21 才真的接上的：`EntityKind` 里一直声明着
   *   "留在地上的区域"，但引擎一处都不读它 —— 于是**持久区域做不出来**，
   *   "靠近的东西自动减速"（无下限术式）、真火墙、毒圈全都卡在这儿。
   *
   * `'area'` 的实体：
   *   · 位置**钉在落点上**（`areapoint` 术式的 `cast.aimPoint`），不跟着召唤者跑
   *   · 每 tick 拿"现在谁在半径内"和上一帧比一次 →
   *     进出的人触发它常驻术式里的 `onEnter` / `onLeave`
   *   · 不参与 AI（`tickAi` 只处理 `'actor'`）
   *   · 不会互相"进入"（一片火墙不会踩进另一片）
   *
   * 想做**跟着人走**的那种（光环），用 `delivery.kind: 'aura'` + `onTick`：
   *   那是"持续施加"，而区域是"进出那一刻触发"。两者的用途不一样，
   *   所以没有合并成一个字段。
   *
   * ⚠ `'obstacle'` 是 2026-09-21 加的（**屏障**）。玩家原话：
   *   > 竖起一道墙抵挡子弹，墙可以有抵挡次数/伤害量、自己的子弹可以穿透而不被抵挡；
   *   > 而且玩家可以决定自己的子弹能否穿过墙、敌人的子弹能否穿墙、以及敌人和友方能否穿墙。
   *
   * 它和 `'area'` 的区别是**它挡东西**：
   *   · 挡子弹（`block.*Projectiles`）
   *   · 挡人（`block.*Units`）—— 把撞上去的人推出来
   *   而 `'area'` 只是"一个范围"，从来不妨碍任何东西穿过。
   *
   * ⚠ "谁能穿过去"是**按阵营比出来的**，不是四个开关随便配：
   *   同阵营走 `own*`，敌对阵营走 `enemy*`。这样召唤者被魅惑（改阵营）之后，
   *   他的墙对新阵营来说仍然是"自己的墙"—— 和纪律 1 一致。
   */
  kind?: 'actor' | 'area' | 'obstacle'
  /**
   * **形状**。不写就是一个圆（半径交给 `radius`，默认 0.4）。
   *
   * ⚠ 一堵"墙"必须是**线段**，不是圆 —— 一排圆拼出来的墙会有缝，
   *   子弹从缝里钻过去，而作者完全看不出为什么漏。
   */
  shape?: EntityShape
  /**
   * **谁能穿过它**（只有 `kind: 'obstacle'` 读它）。
   *
   * ⚠ 每一条都是"**能不能穿过去**"，不是"挡不挡" ——
   *   名字的方向很重要：写 `true` = 放行。四个默认值是刻意的：
   *   · 自己的子弹：**放行**（不然你打不到墙那边的敌人，这是纯亏）
   *   · 敌人的子弹：**挡住**（这就是墙的意义）
   *   · 敌人 / 友方（人）：**放行**（挡人是很大的行为，要显式开）
   *
   * ⚠ 它们**都进点数账**（见 `pricing.ts`）：放行敌人的子弹 = 你少了一份保护，
   *   那是**代价**，提供额度；挡住 = **收益**，消耗额度。
   */
  block?: BlockPolicy
  /** 这个实体拥有的术式 */
  techniques?: string[]
  /**
   * 被召唤出来就挂上的常驻术式（被动）。
   *
   * ⚠ 和 `techniques` 的区别：`techniques` 是"会放"，这只是"已经在生效"。
   *   召唤物的被动必须走这里，否则它挨打时钩子还没挂上。
   */
  activeTechniques?: string[]
  /** AI 配置 */
  ai?: AiProfile
  /*
   * ⚠ 这里原来有个 `baseZ?: number`（"视觉 z 偏移的基准，击飞/浮空用"）。
   *   删掉了 —— **引擎一处都不读它**（`node .scratch/audit-fields.mjs` 报出来的）。
   *
   *   玩家 2026-09-21 给了一条原则：
   *   > 如果改变技能的某种属性不会改变技能的效果（或非常不明显），
   *   > 那这个属性可以固定而不进入编辑器供玩家修改。
   *
   *   它比"编辑器里的死滑块"更糟：它连编辑器都进不去，纯粹是一张空头支票 ——
   *   内容作者照着写，然后发现击飞高度一点没变。等浮空真的要做的时候再加。
   */
  /**
   * 碰撞半径，米。不写用引擎默认的 0.4。
   *
   * ⚠ 它不只是画面大小：目标选择、击退落点、范围技能的命中判定
   *   全都读它。做大体型召唤物（石像鬼、巨人）必须写这个。
   */
  radius?: number
  /**
   * 这个实体**天生**带的伤害管线钩子。
   *
   * 用途：不需要状态就能生效的被动。典型两个：
   *   亡灵生物  —— heal 进来时反转成伤害
   *   龟壳 Boss —— 常驻的伤害修正（缩壳那个是状态，这里是"能缩壳"的底子）
   *
   * 所以管线钩子现在有三个来源：技能图（第 4 步）、状态、实体本身。
   * 这印证了那条纪律：钩子来源不止一个，编译器必须从各处收集再统一排序。
   */
  hooks?: PipelineHook[]
}

/**
 * AI 配置。
 *
 * ⚠ 纪律：AI 必须按"阵营"动态查询目标，绝不硬编码"追玩家"。
 *   写对了，魅惑几乎是免费的；写错了，魅惑要重写所有 AI。
 */
export interface AiProfile {
  /** 目标筛选：按阵营 + 标签 */
  targetFaction: 'enemyOfSelf'
  targetTags?: string[]
  /**
   * 想保持的距离（米）。
   * 太远就往前压，太近就往后撤，差不多就站住放技能。
   * 不写就用 2 米。
   */
  preferredRange?: number
  /** 每隔多久做一次决策（秒）。不写就每 0.25 秒 */
  thinkInterval?: number
  /**
   * 蓄力技蓄多少秒就松手。
   *
   * 蓄力阶段（duration = -1）永远不会自己结束 —— AI 不松手的话，
   * 它会永远举着那把剑。不写就 1.5 秒。
   */
  chargeTime?: number
}

