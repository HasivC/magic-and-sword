/** 载体规格：形状与飞行参数 */
export interface DeliverySpec {
  kind: DeliveryKind
  /**
   * 表现：用哪一条特效。
   *
   * 指向 `content/fx/<id>.json` 里的一条序列帧特效（作者用 AE 之类做的）。
   * **不写就用按载体 + 伤害类型自动挑的程序化特效** ——
   * 所以加了新载体不用马上配特效，也不会变成隐形的。
   *
   * ⚠ 它只影响画面，判定完全不受它影响 —— 改它不该让技能变强或变弱。
   */
  vfx?: string
  /**
   * 扇形/圆形的半径（米）。
   *
   * ⚠ 2026-09-21 起它可以是一个**动态参数**（`{ ref: 'weapon.reach' }`）——
   *   这就是"长剑够得着 3 米、短匕只有 2.2 米"的实现方式：
   *   武器技能模板写 `ref`，具体数值由**装上哪把武器**决定。
   *   写死数字也行（出厂内容里绝大多数还是数字）。
   */
  radius?: number | ValueSpec
  /** 扇形张角（度）。⚠ 它**不是**武器参数（没有 `weapon.angle` 这种 ref），所以还是数字 */
  angle?: number
  /**
   * 光束/胶囊的长度（米）。
   *
   * ⚠ 和 `radius` 同理，可以写 `{ ref: 'weapon.reach' }` ——
   *   刺击那类"线形"招式的够得着，走的就是这一条。
   */
  length?: number | ValueSpec
  /** 光束/胶囊的宽度（米）。⚠ 同上，它也不是武器参数 */
  width?: number
  /** 投射物速度（米/秒） */
  speed?: number
  /** 存在时长（秒） */
  lifetime?: number
  /*
   * ⚠⚠ **这里原来有一个 `count`（"发射数量"）—— 2026-09-30 日志 55 删掉了。**
   *
   *   它是个**死字段**：`describe.ts` 拿它拼描述、`pricing.ts` 那一带也读，
   *   **而引擎根本不读**（`sim/pipeline.ts` 造投射物时只看 `speed` / `lifetime` / `radius`）。
   *   ⇒ 写法上"声明了没人用"，后果是**第二个真相**：
   *     玩家/作者看到 schema 有 `count`，写上去**一点效果都没有**，而且只有
   *     `DELIVERY_FIELD_UNUSED` 那条**警告**兜着（还是后来才补的）。
   *
   *   ⇒ "一次打出好几发"今天**只有一条路**：修饰零件「**一分为 X**」
   *     （`content/modifiers/split.json`，走 `activateGroup` —— 每一份各起一次施法）。
   *     留两条路就是留两个真相，迟早漂移（表现是"我写了 3 发，它只打了 1 发"）。
   *
   *   ⚠ 校验器对**还写着它**的内容报 `BAD_DELIVERY`，话里直接指路「一分为 X」。
   */
  /** 能否穿透目标。⚠ 这个是真的：`sim/projectile.ts` 会读它（默认 `false` = 打中就停） */
  pierce?: boolean
  /*
   * ⚠⚠ **这里原来有一个 `homing`（"追踪"）—— 2026-09-30 日志 56 删掉了。**
   *
   *   它和上面那个 `count` 一样是**死字段**：schema 里写着、`describe.ts` 为它
   *   生成过「追踪」两个字，**而引擎一处都不读**（`spawnProjectile` 只看
   *   `speed` / `lifetime` / `radius` / `pierce`）。
   *
   *   ⇒ 玩家 2026-09-30 裁定：**「追踪」是一件修饰零件**，不是载体上的开关 ——
   *     "正常的技能只沿着发射方向走，而追踪技能**瞄准敌人**"，
   *     而"瞄准 / 找敌人"是**修饰**那一层的事（`ModifierKind` 的 `homing`）。
   *     载体上留一个 `homing` 就是**第二个真相**（和 `count` 的下场逐字相同）。
   *
   *   ⚠ 校验器对**还写着它**的内容报 `BAD_DELIVERY`，话里直接指路修饰零件「追踪」
   *     （见 `src/validator/checks.ts`）。⚠ 引擎里**没有**这个字段的读取点，
   *     也没有它的兜底 —— 删掉它不会让任何既有内容少一个行为。
   */
}

/** 载荷 1/7：伤害 */
export interface DamagePayload {
  kind: 'damage'
  amount: ValueSpec
  /** 伤害类型标签，用于抗性匹配：fire / physical / ... */
  damageType?: string
  /**
   * 伤害模式。
   * 'normal' 普通 | 'lethal' 无视生命值（阿瓦达索命）
   */
  mode?: 'normal' | 'lethal'
}

/** 载荷 2/7：治疗 */
export interface HealPayload {
  kind: 'heal'
  amount: ValueSpec
}

/**
 * 载荷 3/7：属性
 *
 * 这是"属性系统"在规则里的唯一入口。露娜的 CD 重置、暴击叠层、
 * 能量增减、移速修改 —— 全部走这一条。
 *
 * 不要为"改能量"单独开一种载荷：能量只是一个属性，
 * 生命、CD、暴击率也都是。统一成本更低。
 */
export interface AttributePayload {
  kind: 'attribute'
  /** 点分路径：'char.energy.current' / 'char.critDamage' / 'skill.cooldown' */
  path: string
  /** op 为 'reset' 时表示"恢复成本技能的初始冷却"（露娜的大招刷新） */
  op: ModifierOp
  value: ValueSpec
}

/** 载荷 4/7：状态（施加或移除） */
export interface StatusPayload {
  kind: 'status'
  /** 引用内置状态，或内联定义（见 StatusDef） */
  statusId?: string
  inline?: StatusDef
  /** 施加还是移除 */
  verb: 'apply' | 'remove'
  /** 层数 */
  stacks?: number
}

/** 载荷 5/7：位移 */
export interface DisplacementPayload {
  kind: 'displacement'
  /** 击退 / 拉拽 / 传送 / 跳跃 */
  mode: 'knockback' | 'pull' | 'teleport' | 'dash'
  distance: ValueSpec
  /** 是否附带击飞（需要一个视觉 z 偏移） */
  airborne?: boolean
  /**
   * **以谁为落点的锚**。不写就是 `'self'`（沿施法者自己的朝向走 `distance` 米）。
   *
   * ⚠ 玩家 2026-09-21 要的"瞬移到标记敌人**身后**"逼出来的：
   *   `teleport` / `dash` 原来只有"沿我自己朝前闪 N 米"这一种写法，
   *   而"到那个人的身后"要的是**以目标的位置和朝向算落点**。
   *
   * ⚠ `anchor: 'target'` 时必须有目标（动作的 `target` / 术式选出来的那个）。
   *   没目标就**什么都不发生** —— 不是"退化成朝前闪"：
   *   那会让"标丢了还瞬移出去"变成一种随机传送，而玩家完全不知道为什么。
   */
  anchor?: 'self' | 'target'
  /**
   * 相对锚点的**哪一侧**（只有 `anchor: 'target'` 时读）。
   *
   *   `behind` 目标背后（= 目标朝向的反方向）—— "瞬移到身后"就是它
   *   `front`  目标面前
   *   `left` / `right` 目标的两侧（以它的朝向为准）
   *
   * 不写默认 `behind`：会写 `anchor: 'target'` 的人，十有八九想绕到背后。
   */
  side?: 'behind' | 'front' | 'left' | 'right'
}

/** 载荷 6/7：感知 */
export interface PerceptionPayload {
  kind: 'perception'
  /** 透视 / 标记 / 改可见性 */
  mode: 'reveal' | 'mark' | 'setVisibility'
  /** setVisibility 时用：0 = 完全隐形 */
  value?: ValueSpec
  duration?: number
}

/** 载荷 7/7：生成实体 */
export interface SpawnPayload {
  kind: 'spawn'
  /** 引用一个实体定义 id（不做玩家自定义 AI 的召唤物） */
  entityId: string
  count?: number
  /** 生命周期：固定时长 / 直到主人死亡 / 永久 */
  lifetime?: number | 'untilCasterDies' | 'permanent'
}

/** 七种载荷，其余全是 StatusDef 的变体 */
export type Payload =
  | DamagePayload | HealPayload | AttributePayload | StatusPayload
  | DisplacementPayload | PerceptionPayload | SpawnPayload

/** 一次动作 = 载体 + 载荷 + 目标 + 数值 */
export interface Action {
  payload: Payload
  /** 不填则继承术式的载体 */
  delivery?: DeliverySpec
  /**
   * 这条动作打到谁身上。
   *
   * ⚠ 这和 Targeting 不是一回事，别混：
   *   Targeting  回答"施法时怎么选中目标"（指向 / 锁定 / 自动 / 地面点）
   *   这个字段   回答"这条动作作用在谁身上"
   *
   *   'hit'（默认）—— 这次命中里"对面那个"：
   *                   被打侧的钩子 → 打人的人（反伤靠它）
   *                   打人侧的钩子 → 被打的人
   *   'self'        —— 宿主自己（吸血、给自己挂无敌）
   */
  target?: 'hit' | 'self'
  /**
   * 这条动作对谁有效，不写就继承**这个技能的** `targeting.valid`。
   *
   * 为什么需要它：技能的 `targeting` 是给"这个技能怎么用"定的，
   * 但一条规则的目标可能不一样。典型例子是「无下限」——
   * 技能本身是自我增益（`valid: ['self']`），
   * 但它的光环规则要打敌人（`valid: ['enemy']`）。
   * 没有这个字段的话，光环会挂到自己身上。
   *
   * ⚠ 2026-09-21（日志 47）之前它继承的是**术式**的 `targeting.valid`；
   *   瞄准搬到技能层之后，那份有效目标也跟着在技能上了 ——
   *   引擎读的仍然是**编译产物**里那一份（编译时从技能取），
   *   所以这份动作的语义一个字没变（`pipeline.ts` 的 `ctx.validTargets`）。
   */
  valid?: string[]
  /** 给载荷里的 ValueSpec 提供一个默认值（可选） */
  value?: ValueSpec
}


