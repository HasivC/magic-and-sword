/**
 * 引擎的**结算预算**（触发链深度上限）—— 四个消费者读的**同一个数**（2026-09-30 日志 58）。
 *
 * ## 为什么它从 `sim/pipeline.ts` 搬到了这个**叶子模块**
 *
 * 这个数原来只住在 `sim/pipeline.ts`（`MAX_ACTION_DEPTH = 4`），因为当时只有
 * **一个**消费者：`executeAction` 的开头那一句截断。日志 58 的「弹射」是
 * **第二个**消费者，而且它要的读法是"**这个零件最多能弹几次**"——
 * 于是这个数必须同时被下面四层读到：
 *
 * | 谁 | 读它干什么 |
 * | --- | --- |
 * | `sim/pipeline.ts` | 嵌套伤害 / 连锁的截断（原来的那个消费者，**行为一字不变**） |
 * | `sim/pipeline.ts` | 弹射的发射那一刻：`left = min(数据要的, 这个数)` |
 * | `src/school.ts` | 弹射参数的**夹取上限**（`modifierBounceMaxCountOf`） |
 * | `src/validator/*` | 弹射原型的上限**只能小于等于**它（越了要报错，不许静默） |
 * | `src/pricing.ts` | 账按**夹过之后**的次数收（账和引擎必须是同一个数） |
 *
 * ⚠⚠ **为什么不能各写一份**（玩家 2026-09-30 的硬命令）：
 *   弹射是一条**链**，而链上每一段都是一颗新子弹 —— 它**不会**让
 *   `executeAction` 的 `depth` 自然累加。所以"弹射自己的上限"就是这条链
 *   **唯一**的刹车：各写一份的话，迟早出现"改大了弹射的次数 ⇒ 它绕过深度保护
 *   ⇒ 自反馈"（一次施法打到天荒地老）。
 *   ⇒ 判据只有一处，就是这个文件。
 *
 * ⚠ **它必须是一个不 import 任何东西的叶子模块**：
 *   `src/school.ts` 是**纯函数模块**（只 `import type`），而它被编辑器
 *   （`web/src/**`）import —— 让 school 去 import `sim/pipeline.ts` 会把
 *   整张 sim 图拖进来、还会造出 `school → pipeline → compile → school` 的环。
 *   这个文件不 import 任何东西 ⇒ 谁都能读它，且**读它不带来任何别的依赖**。
 *
 * ⚠ `sim/pipeline.ts` 仍然**导出**它（`export { MAX_ACTION_DEPTH }`）——
 *   原来那个 import 路径一个字都不用改。
 */

/**
 * 触发链深度上限。
 *
 * 没有它，"命中时附带子技能，子技能命中时又……" 会无限递归，
 * 一帧之内把栈打爆。前面讨论里管这个叫"结算预算"。
 *
 * ⚠ **值一个字节都没改**（还是 4）：这一片只是把它的**定义处**挪出来，
 *   让弹射能和它读同一个数 —— 不是一次平衡改动。
 */
export const MAX_ACTION_DEPTH = 4
