/** valid 列表里的保留字。其他字符串一律当实体标签匹配（undead / boss ……） */
export const VALID_SELF = 'self'
export const VALID_ALLY = 'ally'
export const VALID_ENEMY = 'enemy'
export const VALID_ANY = 'any'

/** 这个实体算不算 caster 的"敌方"。魅惑就是改 faction，这里自动跟着变 */
export function isHostileTo(caster: Entity, e: Entity): boolean {
  const mine = factionOf(caster)
  const theirs = factionOf(e)
  if (theirs === 'neutral' || mine === 'neutral') return false
  return theirs !== mine
}

/** 目标是否满足 valid 过滤 */
export function matchesValid(caster: Entity, e: Entity, valid: readonly string[]): boolean {
  if (valid.length === 0) return false
  if (valid.includes(VALID_ANY)) return true

  for (const v of valid) {
    switch (v) {
      case VALID_SELF:
        if (e.id === caster.id) return true
        break
      case VALID_ALLY:
        if (e.id !== caster.id && factionOf(e) === factionOf(caster)) return true
        break
      case VALID_ENEMY:
        if (isHostileTo(caster, e)) return true
        break
      default:
        if (e.tags.includes(v)) return true
        break
    }
  }
  return false
}

