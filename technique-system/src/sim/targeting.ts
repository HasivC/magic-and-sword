/**
 * cos(度)。查表 + 线性插值。
 *
 * 为什么不直接用 Math.cos：规范**不保证**它跨 JS 引擎逐位一致，
 * 用了会破坏重放和联机同步。purity 测试也会拦下来。
 * 扇形张角不会超过 180 度，所以只需要 0~90 度。
 */
export function cosDegrees(deg: number): number {
  const a = deg < 0 ? -deg : deg
  if (a >= 90) return 0
  const idx = a / COS_STEP
  const lo = Math.floor(idx)
  const t = idx - lo
  const loV = COS_TABLE[lo] ?? 1
  const hiV = COS_TABLE[lo + 1] ?? 0
  return loV + (hiV - loV) * t
}

