/**
 * **整圈**查表：把任意角度折进 `[0, 360)` 再取最近的那一格（**步长 1 度**）。
 *
 * ⚠ 折角用取模，**不用三角函数**（purity 白名单里没有 `sin` / `cos`）。
 *   `((deg % 360) + 360) % 360` 对负数角度也对（JS 的 `%` 保留被除数符号）。
 *
 * ⚠⚠ **2026-09-30 日志 56：步长从 5 度改成 1 度**（玩家裁定）。为什么必须改：
 *   5 度一格意味着"**比一格还细的角度根本表达不出来**"——
 *   「追踪」的转速参数当时只能把下限抬到 5（"每 tick 转 2 度"会被吸成 **0** ⇒
 *   子弹**设了转速却完全直飞**，而那正是这一整轮在清的**静默失效**）。
 *   ⇒ 做细到 1 度之后，"1 度"成了一个真实的刻度，转速的下限才能回到 1。
 *   ⚠ **精度换的是可重放性**：1 度的量化误差（±0.5 度）已经小到任何玩法都看不出来，
 *     而表仍然是**烘死的常量**（不是运行期 `Math.cos`）⇒ 跨 JS 引擎逐位一致这条没丢。
 *   ⚠ **代价**：`FULL_COS_TABLE` / `FULL_SIN_TABLE` 的取值**整体换了一份**
 *     （361 项、按 15 位小数烘），所以**任何走 `rotate2` 的角度现在会落在更细的格上** ——
 *     「排布」的环绕 / 散射 / 镜像因此在数值上会差不到一格（≤2.5 度 → ≤0.5 度），
 *     那是**精度提高**、不是行为变歪（`meleeArc` 那条路走的是另一张 `COS_TABLE`，
 *     **一个字都没动**）。
 *
 * ⚠ 步长 1 度 ⇒ 任意角度被**吸到最近的整数度**（`round` 是白名单里的）。
 *   编辑器的角度旋钮按 1 度走（`layout.json` / `homing.json` 的模板都改成 `step: 1`）。
 */
function turnIndex(deg: number): number {
  const t = ((deg % 360) + 360) % 360
  return Math.round(t) % 360
}

/** 整圈 cos(度)。⚠ 和上面那个 `cosDegrees` 不是同一个函数（那个只到 90 度） */
export function cosDegreesFull(deg: number): number {
  return FULL_COS_TABLE[turnIndex(deg)] ?? 1
}

/** 整圈 sin(度)。⚠ 同上 */
export function sinDegreesFull(deg: number): number {
  return FULL_SIN_TABLE[turnIndex(deg)] ?? 0
}

/**
 * 把一个方向向量**绕原点转 `deg` 度**（逆时针为正，和数学约定一致）。
 *
 * ⚠ 引擎为什么需要它：「排布」零件要把**已经存在的那几份**摆到不同方向，
 *   而"方向"在引擎里是**单位向量**（`cast.facing` / `ResolvedAim.facing`）——
 *   所以这里做的是"转一个向量"，不是"算一个角度"。
 *
 * ⚠ 结果**不归一化**：旋转矩阵是正交的，单位向量转完还是单位向量
 *   （查表取的是最近 1 度那一格，所以严格说长度会差一点点 ——
 *   调用方要拿去发载体时应该自己 `normalize2`，见 `trigger.ts` 的用法）。
 *
 * ⚠ 它只用白名单里的 `Math.round` / `Math.sqrt`（没有 `sin` / `cos`）——
 *   和 `geom.ts` 的注释同一条纪律：这些是 IEEE 754 精确的，跨引擎一定一致。
 */
export function rotate2(v: { x: number; y: number }, deg: number): { x: number; y: number } {
  const c = cosDegreesFull(deg)
  const s = sinDegreesFull(deg)
  return { x: v.x * c - v.y * s, y: v.x * s + v.y * c }
}

// ---------------------------------------------------------------- 区域查询

export interface AreaQuery {
  caster: Entity
  /** 有效目标标签 */
  valid: readonly string[]
  /** 载体规格。不填就是单体 */
  delivery?: DeliverySpec
  /** 载体以谁为中心发射。不填用 caster */
  origin?: Entity
  /**
   * 载体中心的**坐标**。给了它就以它为准，忽略 `origin` 的位置。
   *
   * ⚠ 这是"点地面放技能"（`targeting.mode: 'areapoint'`）需要的东西：
   *   载体不再长在施法者身上，而是锚在玩家点的那块地上。
   *   火墙、暴风雪、传送门都是这一种 —— 之前的引擎根本表达不出来。
   *
   * 仍然带着 `origin` 是因为判定要用它的**归属**（谁的技能、谁的阵营），
   *   只是不用它的位置。
   */
  originPoint?: { x: number; y: number }
  /** 发射朝向。不填用 origin.facing */
  facing?: { x: number; y: number }
  /** 单体模式下优先打谁 */
  preferredId?: number
}

/**
 * 载体几何里的一个数。
 *
 * ⚠ 载体几何（`radius` / `length`）2026-09-21 起可以写**动态参数**：
 *
 *     { "kind": "meleeArc", "radius": { "ref": "weapon.reach" } }
 *
 *   这就是"长剑够得着 3 米、短匕只有 2.2 米"的实现方式 ——
 *   同一份横砍模板，代入不同的武器属性。
 *
 * ⚠ 上下文只有 `self`（施法者）：几何是"从施法者出发能够到多远"，
 *   和"打的是谁"无关。写 `distance` 这种需要目标的 ref 在这里没有意义
 *   （会得到 0）—— 那不是错，只是没必要。
 */
function geomNumber(
  v: number | ValueSpec | undefined,
  fallback: number,
  caster: Entity,
  world: World,
): number {
  if (v === undefined) return fallback
  if (typeof v === 'number') return v
  return resolveValue(v, { world, self: caster })
}

/**
 * 按载体规格找出全部命中目标。
 *
 * 实现了四种形状：
 *   meleeArc  扇形（挥砍）
 *   area      圆形区域（爆炸 / 火墙）
 *   aura      跟随施法者的圆（光环）
 *   beam      有宽度的线段（光束 / 突刺）
 * 投射物不走这里 —— 它真会飞（见 projectile.ts）。
 */
export function resolveTargets(world: World, q: AreaQuery): Entity[] {
  const origin = q.origin ?? q.caster
  const d = q.delivery

  /*
   * 载体中心。默认是 origin 的位置，`originPoint` 给了就用它 ——
   * 这样"点地面"和"长在身上"共用同一套几何判定，只是中心不同。
   */
  const cx = q.originPoint?.x ?? origin.pos.x
  const cy = q.originPoint?.y ?? origin.pos.y

  if (d === undefined || d.kind === 'self') {
    return matchesValid(q.caster, origin, q.valid) ? [origin] : []
  }

  if (d.kind === 'meleeArc') {
    const radius = geomNumber(d.radius, 2, q.caster, world)
    const halfAngle = (d.angle ?? 90) / 2
    const facing = normalize2(q.facing ?? origin.facing)
    const cosLimit = cosDegrees(halfAngle)
    const out: Entity[] = []

    for (const e of world.entities) {
      if (!e.alive) continue
      if (!matchesValid(q.caster, e, q.valid)) continue
      const dx = e.pos.x - cx
      const dy = e.pos.y - cy
      const dist = Math.sqrt(dx * dx + dy * dy)
      if (dist > radius + e.radius) continue

      if (dist > 1e-6) {
        const dir = normalize2({ x: dx, y: dy })
        // 用点积判夹角，不需要 atan2
        if (dot2(facing, dir) < cosLimit) continue
      }
      out.push(e)
    }
    return out
  }

  if (d.kind === 'area' || d.kind === 'aura') {
    const radius = geomNumber(d.radius, 2, q.caster, world)
    const out: Entity[] = []
    for (const e of world.entities) {
      if (!e.alive) continue
      if (!matchesValid(q.caster, e, q.valid)) continue
      const dx = e.pos.x - cx
      const dy = e.pos.y - cy
      if (Math.sqrt(dx * dx + dy * dy) > radius + e.radius) continue
      out.push(e)
    }
    return out
  }

  /*
   * 光束和突刺：一条**有宽度的线段**。
   *
   * 判定用两次投影，不需要三角函数：
   *   along = 目标在朝向上的投影  → 判"在不在长度范围内"
   *   perp  = 目标到射线的垂距    → 判"在不在宽度范围内"
   * 垂距用二维叉积算，不需要 atan2。
   */
  if (d.kind === 'beam' || d.kind === 'capsule') {
    const length = geomNumber(d.length, 5, q.caster, world)
    const halfWidth = (d.width ?? 0.5) / 2
    const facing = normalize2(q.facing ?? origin.facing)
    const out: Entity[] = []

    for (const e of world.entities) {
      if (!e.alive) continue
      if (!matchesValid(q.caster, e, q.valid)) continue

      const dx = e.pos.x - cx
      const dy = e.pos.y - cy
      const along = dx * facing.x + dy * facing.y
      if (along < -e.radius || along > length + e.radius) continue

      const perp = dx * -facing.y + dy * facing.x
      if (Math.abs(perp) > halfWidth + e.radius) continue

      out.push(e)
    }
    return out
  }

  // 投射物走的是"真会飞"那条路（projectile.ts）。这里退化成立即命中单体。
  const preferred = q.preferredId === undefined
    ? undefined
    : world.entities.find(e => e.id === q.preferredId)
  if (preferred !== undefined && preferred.alive && matchesValid(q.caster, preferred, q.valid)) {
    return [preferred]
  }
  return []
}

